#!/usr/bin/env python3
"""Generate the parallel tree RaftTla/: raft's `with_tla` build, proved by the main tree's proofs.

    etc/gen-raft-tla.py            write RaftTla/'s generated files (and delete stale ones)
    etc/gen-raft-tla.py --check    exit 1 if they differ from what would be generated
    etc/gen-raft-tla.py --list     print the generated modules and their sources

Raft has two builds. Without the build tag `with_tla` its trace hooks (`state_trace_nop.go`) are
empty functions; with it (`state_trace.go`) they report events to a `TraceLogger`. The main tree
translates and verifies the build without the tag, the one etcd ships: every result there is about
it. RaftTla/ holds the build with the tag, for raft's TLA+ trace validation
(examples/raft/tracecheck) and nothing else:

- `RaftTla/Code/`, `RaftTla/GeneratedProof/`: the Goose translations (etc/goose.py, projects
  raft-tla and tracecheck: raft's own package and the trace check's harness);
- hand-written modules, the files of RaftTla/ WITHOUT the marker line below: what is specific to
  the build (the trace logger's contract, the hooks' and their helpers' specs and proofs, the
  package initializer), and the trace check's specs and proofs. A hand-written `RaftTla.M` stands
  in place of the main tree's module `M`, if there is one;
- generated modules, the files WITH the marker: copies of the main tree's modules that reach
  raft's translation (its specs, its proofs, and the library modules that import them), with their
  imports redirected into RaftTla. They are the same text, compiled against the other build's
  code: one proof source for both builds. Never edit them: edit the main tree's file and rerun.

Which modules are copied: starting from the hand-written modules of RaftTla/, follow imports; an
import `RaftTla.M` of a module with no file of its own in RaftTla/ is a copy of the main tree's `M`,
whose imports are followed in turn, each one redirected into RaftTla when it names a module that
has a hand-written or translated `RaftTla.` counterpart or that (transitively) imports one. Nothing
may import both a module and its RaftTla counterpart: they declare the same names.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PART = "RaftTla"
MARK = "-- GENERATED by etc/gen-raft-tla.py from "
# The main tree's module roots a copy may come from.
TOPS = ["Code", "GeneratedProof", "TrustedCode", "ManualProof", "Spec", "Proof", "GooseLang"]
IMPORT = re.compile(r"^(\s*(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?)(\S+)(.*)$")


def modules(top_dir, prefix):
    """module name -> path, for the .lean files under `top_dir` (module names prefixed by `prefix`)."""
    out = {}
    for dp, _, fs in os.walk(os.path.join(ROOT, top_dir)):
        for f in fs:
            if f.endswith(".lean"):
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, os.path.join(ROOT, top_dir))
                out[prefix + rel[:-5].replace(os.sep, ".")] = p
    return out


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def imports(text):
    """The modules a file imports (its header: up to the first line that is neither blank, a
    comment, `module`, nor an import)."""
    out = []
    depth = 0
    for line in text.split("\n"):
        s = line.strip()
        if depth > 0:
            depth += s.count("/-") - s.count("-/")
            continue
        if s.startswith("/-"):
            depth += s.count("/-") - s.count("-/")
            continue
        if not s or s.startswith("--") or s == "module":
            continue
        m = IMPORT.match(line)
        if not m:
            break
        out.append(m.group(2).replace("«", "").replace("»", ""))
    return out


def plan():
    main = {}
    for top in TOPS:
        main.update(modules(top, top + "."))
    part_files = modules(PART, PART + ".")
    own = {}      # RaftTla modules that are not generated copies: hand-written or translated
    stale = {}    # generated copies now on disk
    for m, p in part_files.items():
        (stale if read(p).startswith(MARK) else own)[m] = p
    main_imports = {m: imports(read(p)) for m, p in main.items()}
    # U: the main modules that must be compiled again for RaftTla: those with a RaftTla counterpart
    # of their own, and their transitive importers.
    rev = {}
    for m, ds in main_imports.items():
        for d in ds:
            rev.setdefault(d, []).append(m)
    counterpart = {m[len(PART) + 1:] for m in own}
    U = set()
    stack = [m for m in counterpart]
    while stack:
        x = stack.pop()
        for y in rev.get(x, []):
            if y not in U:
                U.add(y)
                stack.append(y)
    U |= {m for m in counterpart if m in main}

    def redirect(mod):
        """The module an import of the main tree's `mod` becomes in RaftTla."""
        if mod in counterpart or mod in U:
            return PART + "." + mod
        return mod

    # the copies needed: from the hand-written modules, by imports
    copies = {}   # main module -> RaftTla module
    seen = set()
    stack = list(own)
    errors = []
    while stack:
        m = stack.pop()
        if m in seen:
            continue
        seen.add(m)
        if m in own:
            deps = imports(read(own[m]))
        else:
            src = m[len(PART) + 1:]
            deps = [redirect(d) for d in main_imports[src]]
        for d in deps:
            if not d.startswith(PART + "."):
                # a main-tree module imported from RaftTla must not need recompiling
                if d in U or d in counterpart:
                    errors.append(f"{m} imports {d}, which has a {PART} counterpart: import {PART}.{d}")
                continue
            if d in own:
                stack.append(d)
                continue
            src = d[len(PART) + 1:]
            if src not in main:
                errors.append(f"{m} imports {d}: no such module in {PART}/ and no main-tree module {src}")
                continue
            copies[src] = d
            stack.append(d)
    return main, own, stale, copies, redirect, errors


def render(src_mod, src_path, redirect):
    rel = os.path.relpath(src_path, ROOT)
    lines = read(src_path).split("\n")
    out = [MARK + rel + "; do not edit (edit that file and rerun)."]
    depth = 0
    header = True
    for line in lines:
        if header:
            s = line.strip()
            if depth > 0 or s.startswith("/-"):
                depth += s.count("/-") - s.count("-/")
            elif s and not s.startswith("--") and s != "module":
                m = IMPORT.match(line)
                if m:
                    mod = m.group(2).replace("«", "").replace("»", "")
                    line = m.group(1) + redirect(mod) + m.group(3)
                else:
                    header = False
        out.append(line)
    return "\n".join(out)


def main_():
    check = "--check" in sys.argv
    main, own, stale, copies, redirect, errors = plan()
    for e in errors:
        if "--fix-imports" not in sys.argv:
            print("gen-raft-tla: " + e, file=sys.stderr)
    if errors and "--fix-imports" not in sys.argv:
        sys.exit(1)
    if "--fix-imports" in sys.argv:
        # redirect the imports of the hand-written modules (after moving a file into RaftTla/)
        n = 0
        for m, path in own.items():
            if os.sep + "Code" + os.sep in path or os.sep + "GeneratedProof" + os.sep in path:
                continue
            lines = read(path).split("\n")
            new = []
            depth = 0
            header = True
            for line in lines:
                if header:
                    s = line.strip()
                    if depth > 0 or s.startswith("/-"):
                        depth += s.count("/-") - s.count("-/")
                    elif s and not s.startswith("--") and s != "module":
                        mm = IMPORT.match(line)
                        if mm:
                            mod = mm.group(2).replace("«", "").replace("»", "")
                            if not mod.startswith(PART + "."):
                                line = mm.group(1) + redirect(mod) + mm.group(3)
                        else:
                            header = False
                new.append(line)
            if new != lines:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write("\n".join(new))
                n += 1
        print(f"gen-raft-tla: imports redirected in {n} hand-written module(s)")
        return
    if "--list" in sys.argv:
        for src in sorted(copies):
            print(copies[src], "<-", os.path.relpath(main[src], ROOT))
        return
    want = {}
    for src, dst in copies.items():
        path = os.path.join(ROOT, dst.replace(".", os.sep) + ".lean")
        want[path] = render(src, main[src], redirect)
    changed = [p for p, c in want.items() if not os.path.exists(p) or read(p) != c]
    gone = [p for p in stale.values() if p not in want]
    if check:
        for p in changed:
            print("gen-raft-tla: out of date: " + os.path.relpath(p, ROOT))
        for p in gone:
            print("gen-raft-tla: stale: " + os.path.relpath(p, ROOT))
        if changed or gone:
            print(f"gen-raft-tla: FAILED ({len(changed)} out of date, {len(gone)} stale; run etc/gen-raft-tla.py)")
            sys.exit(1)
        print(f"gen-raft-tla: {len(want)} generated modules up to date ({len(own)} hand-written or translated)")
        return
    for p in changed:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(want[p])
    for p in gone:
        os.remove(p)
    print(f"gen-raft-tla: {len(want)} generated modules ({len(changed)} written, {len(gone)} removed; "
          f"{len(own)} hand-written or translated)")


if __name__ == "__main__":
    main_()
