#!/usr/bin/env python3
"""Generate SpecPlan/Spec/PkgInit/<pkg path>.lean: the `IsPkgInit` instance of every translated
package that Perennial does not already give one, for the spec plan (the part `SpecPlan/`).

Each package's user part is the opaque `PkgInit.pkgInitDef pkg_id.X` (SpecPlan/Spec/PkgInit/Base.lean):
what a package's globals satisfy after its initializer is part of the specs (a law of the package
that needs it, `<pkg>.init.spec`), not fixed here. The dependency part is computed by Perennial's
`define_is_pkg_init` from the package's `PkgInfo` (`pkgImportedPkgs`), so every dependency's
instance must be in scope: the module imports the dependencies' PkgInit modules (or Perennial's
`Perennial.Proof.<pkg>.Base` for a standard-library package Perennial covers).

Usage: etc/gen-specs-pkginit.py [--check]   (--check: exit 1 if a module differs, writing nothing)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PER = os.path.join(ROOT, ".lake", "packages", "perennial")

def scan_pkginfo(base, code_dir):
    """pkg -> list of imported pkgs, from `instance info' : PkgInfo pkg_id.X where pkgImportedPkgs := [...]`."""
    out = {}
    for dp, _, fs in os.walk(os.path.join(base, code_dir)):
        for f in fs:
            if not f.endswith(".lean"):
                continue
            s = open(os.path.join(dp, f), encoding="utf-8").read()
            for m in re.finditer(r"instance info' : PkgInfo pkg_id\.([A-Za-z0-9_.«»]+) where\s*\n\s*pkgImportedPkgs := \[(.*?)\]", s, re.S):
                deps = re.findall(r"pkg_id\.([A-Za-z0-9_.«»]+)", m.group(2))
                out[m.group(1)] = deps
    return out

def perennial_instances():
    """pkg -> Perennial module giving its IsPkgInit instance."""
    out = {}
    for dp, _, fs in os.walk(os.path.join(PER, "Perennial", "Proof")):
        for f in fs:
            if not f.endswith(".lean"):
                continue
            p = os.path.join(dp, f)
            s = open(p, encoding="utf-8").read()
            for m in re.finditer(r"IsPkgInit \(IProp GF\) pkg_id\.([A-Za-z0-9_.«»]+)\s*:=", s):
                mod = os.path.relpath(p, PER)[:-5].replace("/", ".")
                out.setdefault(m.group(1), mod)
    return out

def fpath(pkg):
    return pkg.replace("«", "").replace("»", "").replace(".", "/")

def genproof_module(pkg, ours):
    path = fpath(pkg)
    if os.path.exists(os.path.join(ROOT, "GeneratedProof", path + ".lean")):
        return "GeneratedProof." + pkg
    if os.path.exists(os.path.join(PER, "Perennial", "GeneratedProof", path + ".lean")):
        return "Perennial.GeneratedProof." + pkg
    return None


DUP_LAST = set()
def inst_name(pkg):
    if pkg.split(".")[-1] in DUP_LAST:
        return "pkgInit_" + pkg.replace(".", "_").replace("«", "").replace("»", "") + " "
    return ""

def main():
    check = "--check" in sys.argv
    ours = scan_pkginfo(ROOT, "Code")
    theirs = scan_pkginfo(os.path.join(PER, "Perennial"), "Code")
    info = dict(theirs); info.update(ours)
    pinst = perennial_instances()
    # A package this repository translates itself (Code/<pkg>.lean: os, io/fs, net/http, ...) is
    # not Perennial's: its names clash with Perennial's translation, so its instance is local.
    for pkg in ours:
        if os.path.exists(os.path.join(ROOT, "GeneratedProof", fpath(pkg) + ".lean")):
            pinst.pop(pkg, None)
    lasts = {}
    for pkg in info:
        if pkg in pinst: continue
        if genproof_module(pkg, ours) is None: continue
        l = pkg.split(".")[-1]
        lasts[l] = lasts.get(l, 0) + 1
    DUP_LAST.update(l for l, n in lasts.items() if n > 1)
    want = {}
    for pkg in sorted(info):
        if pkg in pinst:
            continue
        gp = genproof_module(pkg, ours)
        if gp is None:
            print(f"skip {pkg}: no GeneratedProof module", file=sys.stderr)
            continue
        imports = [gp, "SpecPlan.Spec.PkgInit.Base"]
        for d in info[pkg]:
            if d in pinst:
                imports.append(pinst[d])
            else:
                imports.append("SpecPlan.Spec.PkgInit." + d)
        body = f"""-- generated by etc/gen-specs-pkginit.py; do not edit
module

{chr(10).join('public import ' + i for i in dict.fromkeys(imports))}

@[expose] public section
noncomputable section

namespace Perennial
namespace EtcdGrove
namespace PkgInit
open Iris Iris.BI

section
variable [GooseExts] [GooseSemantics] [GooseInterp]
variable [go_gctx : GoGlobalContext]
variable {{hlc : HasLC}} {{GF : BundledGFunctors}} [hG : HeapGS hlc GF]
variable [sem : go.Semantics]

instance {inst_name(pkg)}: IsPkgInit (IProp GF) pkg_id.{pkg} :=
  define_is_pkg_init (pkgInitDef (GF := GF) pkg_id.{pkg})
end

end PkgInit
end EtcdGrove
end Perennial
"""
        want[os.path.join(ROOT, "SpecPlan", "Spec", "PkgInit", fpath(pkg) + ".lean")] = body
    bad = 0
    for p, body in want.items():
        old = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if old != body:
            if check:
                print("differs:", os.path.relpath(p, ROOT)); bad = 1
            else:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                open(p, "w", encoding="utf-8").write(body)
    if not check:
        print(f"{len(want)} PkgInit modules")
    sys.exit(bad)

if __name__ == "__main__":
    main()
