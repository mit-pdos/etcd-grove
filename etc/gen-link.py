#!/usr/bin/env python3
"""Generate EtcdGrove/Raft/Link.lean from the proofs' callee hypotheses.

Each Go function <fn> has `Spec/<fn>.lean` (`abbrev <T>.<M>.spec`) and
`Proof/<fn>.lean` (`theorem <T>.<M>.wp_proof (wp_C₁ : C₁.spec …) … : <T>.<M>.spec …`,
or an `axiom` at the trust boundary). The result of <fn> is its `wp_proof` applied to
the callees' results, in the order of its hypotheses:

    theorem <T>.wp_<M> : <T>.<M>.spec (GF := GF) (hG := hG) := <T>.<M>.wp_proof <callees>

(Until 2026-10-08 the callees came from the Rocq `postulates_*.v`; the Lean proofs'
hypotheses are in the same order, and Lean is now the primary development.)

usage: etc/gen-link.py [--check]
  writes EtcdGrove/Raft/Link.lean; with --check, only compares and exits 1 if the
  file is out of date.
"""
import glob
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
lean = os.path.join(here, "..", "EtcdGrove", "Raft")
LINK = os.path.join(lean, "Link.lean")
NAME = r"[\w.«»']+"

fns = sorted(os.path.basename(f)[:-5] for f in glob.glob(os.path.join(lean, "Spec", "*.lean")))

spec = {}
for fn in fns:
    m = re.search(r"^abbrev ([\w.«»]+)\.spec\b", open(os.path.join(lean, "Spec", f"{fn}.lean")).read(), re.M)
    if not m:
        sys.exit(f"Spec/{fn}.lean: no `abbrev <name>.spec`")
    spec[fn] = m.group(1)
byspec = {spec[fn]: fn for fn in fns}

callees = {}
for fn in fns:
    path = os.path.join(lean, "Proof", f"{fn}.lean")
    if not os.path.exists(path):
        sys.exit(f"Spec/{fn}.lean has no Proof/{fn}.lean")
    # The hypotheses run up to the conclusion, `: <own spec>.spec`.
    m = re.search(rf"^(?:theorem|axiom) {re.escape(spec[fn])}\.wp_proof\b(.*?)"
                  rf"\s:\s*{re.escape(spec[fn])}\.spec\b",
                  open(path).read(), re.M | re.S)
    if not m:
        sys.exit(f"Proof/{fn}.lean: no `{spec[fn]}.wp_proof`")
    hyps = re.findall(rf"\(\s*\w+\s*:\s*({NAME})\.spec\b", m.group(1))
    unknown = [h for h in hyps if h not in byspec]
    if unknown:
        sys.exit(f"Proof/{fn}.lean: hypotheses {unknown} are not the spec of any Spec/ file")
    callees[fn] = [byspec[h] for h in hyps]

# The specs stated at `HeapGS HasLC.hasLC GF` (the ghost state holds an invariant).
haslc = {fn for fn in fns
         if "HeapGS HasLC.hasLC" in open(os.path.join(lean, "Spec", f"{fn}.lean")).read()}


def result(fn):
    """`a.b.M` ↦ `a.b.wp_M`, `F` ↦ `wp_F`."""
    parts = spec[fn].split(".")
    last = parts[-1].strip("«»")
    return ".".join(parts[:-1] + [f"wp_{last}"])


order, seen, onpath = [], set(), set()


def visit(fn):
    if fn in seen:
        return
    if fn in onpath:
        sys.exit(f"callee cycle through {fn}")
    onpath.add(fn)
    for c in callees[fn]:
        visit(c)
    onpath.discard(fn)
    seen.add(fn)
    order.append(fn)


for fn in fns:
    visit(fn)

out = []
out.append("""/-
Every proof instantiated with its callees' results, in the order of its hypotheses
(the port of `election_proof/election.v` and the `link_*.v` files).
Generated by `etc/gen-link.py` -- do not edit by hand.

`#print axioms` on a result is its trust base: an `axiom` is the trust boundary (the
`Proof/<fn>.lean` of a function outside the scope), `sorryAx` is unfinished work.
-/""")
for fn in fns:
    out.append(f"import EtcdGrove.Raft.Proof.{fn}")
out.append("""
noncomputable section

namespace Perennial
namespace EtcdGrove

open Iris Iris.BI go_etcd_io.raft.v3
""")

VARS = """variable [ext : FfiSyntax] [ffi : FfiModel] [FfiInterp ffi] [FfiSemantics ext ffi]
variable [go_gctx : GoGlobalContext]
{heap}
variable [sem : go.Semantics]
variable [package_sem : go_etcd_io.raft.v3.Assumptions]
"""


def emit(fn):
    args = " ".join(result(c) for c in callees[fn])
    body = f"{spec[fn]}.wp_proof" + (f" {args}" if args else "")
    return (f"theorem {result(fn)} :\n    {spec[fn]}.spec (GF := GF) (hG := hG) :=\n"
            f"  {body}\n")


generic = [fn for fn in order if fn not in haslc]
special = [fn for fn in order if fn in haslc]
bad = [(fn, c) for fn in generic for c in callees[fn] if c in haslc]
if bad:
    sys.exit(f"a generic spec's proof uses a HasLC.hasLC spec: {bad}")
out.append("section links\n" + VARS.format(
    heap="variable {hlc : HasLC} {GF : BundledGFunctors} [hG : HeapGS hlc GF]\nvariable [AllG GF]"))
out.extend(emit(fn) for fn in generic)
out.append("end links\n")
out.append("""/-! The specs stated at `HeapGS HasLC.hasLC GF`: the ghost state holds an
invariant (`raftCommitInv`), whose world is the heap's only at `.hasLC`. -/""")
out.append("section links_hasLC\n" + VARS.format(
    heap="variable {GF : BundledGFunctors} [hG : HeapGS HasLC.hasLC GF]\nvariable [AllG GF]"))
out.extend(emit(fn) for fn in special)
out.append("end links_hasLC\n\nend EtcdGrove\nend Perennial")
text = "\n".join(out) + "\n"

if "--check" in sys.argv[1:]:
    if open(LINK).read() != text:
        sys.exit("EtcdGrove/Raft/Link.lean is out of date: run etc/gen-link.py")
else:
    with open(LINK, "w") as f:
        f.write(text)
