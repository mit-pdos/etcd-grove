#!/usr/bin/env python3
"""Generate EtcdGrove/Btree/Link.lean: every btree proof applied to its callees' results.

Each `EtcdGrove/Btree/Proof/<fn>.lean` proves `theorem <S>.wp_proof (h : <C>.spec ...) ... :
<S>.spec`; its hypotheses (the specs of the Go functions it calls) are read off the
theorem's binders, in order. The result of `<S>` (`a.b.M`) is `a.b.wp_M` (`F`: `wp_F`):

    theorem <T>.wp_<M> : <T>.<M>.spec (GF := GF) (hG := hG) := <T>.<M>.wp_proof <callees>

A Proof file may prove several specs (mutually recursive functions); every `wp_proof` in it
is linked. A spec with no proof yet is left out, with the results that need it.

usage: etc/gen-btree-link.py > EtcdGrove/Btree/Link.lean
"""
import glob
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
lean = os.path.join(here, "..", "EtcdGrove", "Btree")

THM = re.compile(r"^theorem ([\w.«»']+)\.wp_proof\b(.*?):=", re.M | re.S)
HYP = re.compile(r"\(\s*\w+\s*:\s*([\w.«»']+)\.spec\b")

proofs = {}  # spec name -> (module, callees)
for path in sorted(glob.glob(os.path.join(lean, "Proof", "*.lean"))):
    mod = os.path.basename(path)[:-5]
    src = open(path).read()
    for m in THM.finditer(src):
        head = m.group(2)
        # the binders end at the colon that starts the statement `... : <S>.spec`
        callees = HYP.findall(head)
        if callees and callees[-1] == m.group(1):
            callees = callees[:-1]
        proofs[m.group(1)] = (mod, callees)


def result(spec):
    parts = spec.split(".")
    return ".".join(parts[:-1] + [f"wp_{parts[-1].strip('«»')}"])


order, seen, missing = [], set(), set()


def visit(s):
    if s in seen:
        return s not in missing
    seen.add(s)
    if s not in proofs:
        missing.add(s)
        return False
    ok = all([visit(c) for c in proofs[s][1]])
    if not ok:
        missing.add(s)
        return False
    order.append(s)
    return True


for s in sorted(proofs):
    visit(s)

out = ["""/-
The btree proofs, each instantiated with its callees' results. Generated by
`etc/gen-btree-link.py` -- do not edit by hand.

`#print axioms` on a result is its trust base (`sorryAx` is unfinished work).
-/"""]
for mod in sorted({proofs[s][0] for s in order}):
    out.append(f"import EtcdGrove.Btree.Proof.{mod}")
out.append("""
noncomputable section

namespace Perennial
namespace EtcdGrove
namespace Btree

open Iris Iris.BI github_com.google.btree

section links
variable [ext : FfiSyntax] [ffi : FfiModel] [FfiInterp ffi] [FfiSemantics ext ffi]
variable [go_gctx : GoGlobalContext]
variable {hlc : HasLC} {GF : BundledGFunctors} [hG : HeapGS hlc GF]
variable [sem : go.Semantics]
variable [package_sem : github_com.google.btree.Assumptions]
""")
for s in order:
    args = " ".join(result(c) for c in proofs[s][1])
    body = f"{s}.wp_proof" + (f" {args}" if args else "")
    out.append(f"theorem {result(s)} :\n    {s}.spec (GF := GF) (hG := hG) :=\n  {body}\n")
out.append("end links\n\nend Btree\nend EtcdGrove\nend Perennial")
print("\n".join(out))
if missing:
    print(f"gen-btree-link.py: not linked (unproved, or needing an unproved spec): "
          f"{', '.join(sorted(missing))}", file=sys.stderr)
