#!/usr/bin/env python3
"""gomodels: the Go model overlays of etcd-grove's goose configs (Perennial's `[model]` tables).

A package's goose config (`<root>/Code/<pkg>.toml`) may have a `[model]` table (Perennial
goose/README.md, "Go model overlays"): Go model files that replace declarations of the real package
(`replaces`) or only add to it (`replaces = []`), in `dir`, relative to the repository root. The
models of this repository live at `models/<import path>/` (each top-level directory a Go module that
nothing builds), and a generated one (jsongen's same-package methods) at the generator's output
directory under `models/`, committed and regenerated by `etc/goose.py --check`.

The standard-library models' choice and stuck points are Perennial's `internal/gomodel` (`Choose`,
`ChooseUint64`, `Stuck`), a package the overlay adds to the standard library. Its Go files are not
copied into this repository: every config directory that needs it has an `internal/gomodel.toml`
whose `[model]` dir is GOMODEL_DIR, which this script fills from Perennial's
`goose/model/overlay/internal/gomodel` **at the Lean pin** (lake-manifest.json's perennial rev), the
revision whose `Perennial.Code.internal.gomodel` (the translation and its TrustedCode stubs) the
Lean imports. So the Go and the Lean of internal/gomodel are Perennial's, of one revision.

    etc/gomodels.py materialize [--perennial DIR]
        write GOMODEL_DIR from the pin (taken from DIR's git, or from .lake/packages/perennial, or
        from etc/goose.py's checkout of the pin); prints the directory. etc/goose.py does this
        before every translation.
    etc/gomodels.py check [--perennial DIR]
        exit 1 unless every internal/gomodel.toml of this repository says what the pin's
        Perennial/Code/internal/gomodel.toml says (`translate`, `trusted`, `replaces`), with
        GOMODEL_DIR as its dir (in etc/gates.sh).
    etc/gomodels.py test [--perennial DIR] [NAME...]
        the Go tests of the packages with a Go model (TESTS, below), each run against the package
        with its models spliced in (`goose model-overlay`, the goose of DIR or of the pin): the real
        package's own tests where they apply, and the models' differential tests (etc/model-tests.sh
        runs it; the tests left out are named in TESTS with the reason).
"""

import argparse
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
# Perennial's model of internal/gomodel (its Perennial/Code/internal/gomodel.toml's [model] dir)
PERENNIAL_GOMODEL = "goose/model/overlay/internal/gomodel"
# where the pin's files are put; the `dir` of every internal/gomodel.toml of this repository
GOMODEL_DIR = os.path.join(".lake", "gomodel", "internal", "gomodel")


def pin_rev():
    manifest = json.load(open(os.path.join(ROOT, "lake-manifest.json")))
    (p,) = [p for p in manifest["packages"] if p["name"] == "perennial"]
    return p["rev"]


def _files_at(d, rev):
    """{file name: contents} of PERENNIAL_GOMODEL's Go files at `rev` in the git repository `d`, or
    None if `d` does not have `rev`."""
    if not d or not os.path.isdir(d):
        return None
    r = subprocess.run(["git", "-C", d, "ls-tree", "--name-only", rev + ":" + PERENNIAL_GOMODEL],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return None
    out = {}
    for n in r.stdout.split():
        if n.endswith(".go") and not n.endswith("_test.go"):
            out[n] = subprocess.run(["git", "-C", d, "show", f"{rev}:{PERENNIAL_GOMODEL}/{n}"],
                                    check=True, capture_output=True).stdout
    return out or None


def materialize(candidates=()):
    """Fill GOMODEL_DIR with the pin's internal/gomodel Go files, from the first of `candidates`
    (git checkouts of Perennial) that has the pin, else .lake/packages/perennial, else
    etc/goose.py's checkout of the pin. Returns the directory's absolute path."""
    rev = pin_rev()
    files = None
    for d in list(candidates) + [os.path.join(ROOT, ".lake", "packages", "perennial")]:
        files = _files_at(d, rev)
        if files:
            break
    if not files:
        sys.path.insert(0, os.path.join(ROOT, "etc"))
        import importlib
        goose = importlib.import_module("goose")
        d, _ = goose.pinned_perennial()
        files = _files_at(d, rev)
    if not files:
        sys.exit(f"gomodels.py: no {PERENNIAL_GOMODEL} at Perennial {rev}")
    out = os.path.join(ROOT, GOMODEL_DIR)
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    for n, c in sorted(files.items()):
        with open(os.path.join(out, n), "wb") as f:
            f.write(c)
    return out


# The Go tests of the packages with a Go model: (name, config dir, where the Go module is ("models":
# models/; "project:NAME": etc/goose.py's checkout of the project, in its workspace with models.lab),
# the packages whose models the overlay splices in, the `go test` arguments, why tests are left out).
# Every test runs with the translation's build tags (goose, netgo), unless its arguments give -tags.
TESTS = [
    ("crc32", "Code", "models", ["hash/crc32"], ["hash/crc32"],
     "none left out (TestArchCastagnoli compares archUpdateCastagnoli, the model's portable CRC-32C, "
     "with simpleUpdate: trivially equal under the model)"),
    ("token", os.path.join("Net", "Code"), "models", ["go/token"], ["go/token"],
     "none left out (go/token's own tests do not call IsExported)"),
    # (without the tag goose: rpcdifftest's codec files of that tag need the net/rpc model)
    ("token-diff", os.path.join("Net", "Code"), "models", ["go/token"],
     ["-tags", "netgo", "-run", "^TestIsExportedASCII$", "./internal/rpcdifftest"],
     "IsExported's model against Go's results on every ASCII first byte (non-ASCII is the model's "
     "choice point, gomodel.Choose, whose Go body returns false)"),
    # (S5) os's and syscall's models over the Linux file extension's stubs (the stubs' Go bodies are
    # the real system calls)
    ("os", "Code", "project:bboltfs", ["os", "syscall"],
     ["-run", "^Test(ReadAt|WriteAt|Seek|Truncate|MkdirAll|Remove|RemoveAll|Rename|Stat|Readdirnames)",
      "-skip", "^(TestWriteAtInAppendMode|TestReaddirnamesOneAtATime|TestRemoveAllWithMoreErrorThanReqSize|"
      "TestStatStdin|TestStatDirModeExec|TestSeekError|TestWriteAtConcurrent|TestRemoveAllLongPath|"
      "TestRemoveAllSymlinkRemovalFailure|TestRemoveAllNoFcntl)$", "os"],
     "os's tests of the modelled calls the plan lists (ReadAt, WriteAt, Seek, Truncate, MkdirAll, "
     "Remove, RemoveAll, Rename, Stat, Readdirnames); left out: what reaches gomodel.Stuck, which blocks "
     "forever in gc builds (O_APPEND: TestWriteAtInAppendMode; Readdirnames(n > 0): "
     "TestReaddirnamesOneAtATime, TestRemoveAllWithMoreErrorThanReqSize); a choice whose gc answer is "
     "not Linux's (mode bits, gomodel.ChooseUint64 = 0: TestStatStdin, TestStatDirModeExec); what the "
     "file extension does not model, where the stubs' gc bodies differ from Go (pipes: TestSeekError; "
     "symlinks: TestRemoveAllSymlinkRemovalFailure; paths over PATH_MAX, which RemoveAll's model names "
     "whole where Go uses the *at calls: TestRemoveAllLongPath; a strace child process: "
     "TestRemoveAllNoFcntl); concurrent Write calls, whose offset the model updates without Go's lock "
     "(more outcomes than Go: TestWriteAtConcurrent; models/os/model.go, Write)"),
    ("syscall", "Code", "project:bboltfs", ["os", "syscall"],
     ["-run", "^TestLocks(OFDConflict|OFDRemoveThenClose|OFDSameDescription|Flock|FlockVsOFD)$",
      "github.com/mit-pdos/etcd-grove/examples/osfs/semantics"],
     "the file extension's lock examples over syscall's models of Flock and FcntlFlock (OFD locks); "
     "syscall's own TestFcntlFlock (F_SETLK, F_GETLK: not modelled, gomodel.Stuck, which blocks "
     "forever in Go builds) is left out, and the package has no other test of a modelled call "
     "(Mkdir, Unlink and Rmdir run in the os row's MkdirAll/Remove tests)"),
    ("durable", "Code", "project:durable", ["github.com/mit-pdos/etcd-grove/examples/lib/durable"],
     ["github.com/mit-pdos/etcd-grove/examples/lib/durable"],
     "none left out (durable_test.go; the stubs' Go bodies are Go's Read/Write)"),
]
TAGS = "goose,netgo"


def _goose_bin(candidates, tmp):
    sys.path.insert(0, os.path.join(ROOT, "etc"))
    import importlib
    goose = importlib.import_module("goose")
    perennial = next((d for d in candidates if d), None) or goose.pinned_perennial()[0]
    subprocess.run(["go", "build", "-o", tmp + os.sep, "./goose/cmd/goose"], cwd=perennial,
                   env=goose.host_env(), check=True)
    return os.path.join(tmp, "goose"), goose


def test(candidates=(), names=()):
    import tempfile
    materialize(candidates)
    tmp = tempfile.mkdtemp(prefix="gomodels-")
    try:
        gbin, goose = _goose_bin(candidates, tmp)
        base = dict(os.environ, GOTOOLCHAIN=goose.GO_TOOLCHAIN, GOOS="linux", GOARCH="amd64",
                    CGO_ENABLED="1")
        ok = True
        for name, cfg, where, pkgs, args, why in TESTS:
            if names and name not in names:
                continue
            env, cwd = dict(base), os.path.join(ROOT, "models")
            if where.startswith("project:"):
                (proj,) = [p for p in goose.PROJECTS if p.name == where[len("project:"):]]
                cwd, _ = goose.source(proj, None, False)
                d = os.path.join(tmp, name + "-env")
                os.makedirs(d)
                env = goose.module_models_env(proj, cwd, env, d)
            ov = os.path.join(tmp, name)
            print(f"gomodels: {name}: {why}", file=sys.stderr)
            r = subprocess.run([gbin, "model-overlay", "-configdir", os.path.join(ROOT, cfg),
                                "-model-root", ROOT, "-dir", cwd, "-tags", "netgo", "-o", ov] + pkgs,
                               cwd=cwd, env=env)
            if r.returncode == 0:
                # go vet does not find the overlay-added internal/gomodel (Perennial's
                # etc/model-tests.sh)
                r = subprocess.run(["go", "test", "-vet=off", "-count=1", "-timeout", "600s",
                                    "-overlay", os.path.join(ov, "overlay.json")]
                                   + ([] if "-tags" in args else ["-tags", TAGS]) + args,
                                   cwd=cwd, env=env)
            if r.returncode != 0:
                print(f"gomodels: {name}: FAILED", file=sys.stderr)
                ok = False
        return ok
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# the config directories with an internal/gomodel.toml
CONFIG_DIRS = ["Code", os.path.join("Net", "Code")]


def _toml(text):
    try:
        import tomllib
    except ImportError:
        import tomli as tomllib
    return tomllib.loads(text)


def check(candidates=()):
    rev = pin_rev()
    ref = None
    for d in list(candidates) + [os.path.join(ROOT, ".lake", "packages", "perennial")]:
        if d and os.path.isdir(d):
            r = subprocess.run(["git", "-C", d, "show", rev + ":Perennial/Code/internal/gomodel.toml"],
                               capture_output=True, text=True)
            if r.returncode == 0:
                ref = _toml(r.stdout)
                break
    if ref is None:
        sys.path.insert(0, os.path.join(ROOT, "etc"))
        import importlib
        d, _ = importlib.import_module("goose").pinned_perennial()
        ref = _toml(open(os.path.join(d, "Perennial", "Code", "internal", "gomodel.toml")).read())
    bad = []
    for cd in CONFIG_DIRS:
        f = os.path.join(ROOT, cd, "internal", "gomodel.toml")
        t = _toml(open(f).read())
        for k in ("translate", "trusted"):
            if t.get(k) != ref.get(k):
                bad.append(f"{f}: {k} = {t.get(k)}, Perennial {rev}'s is {ref.get(k)}")
        m, rm = t.get("model", {}), ref.get("model", {})
        if m.get("replaces") != rm.get("replaces") or m.get("dir") != GOMODEL_DIR.replace(os.sep, "/"):
            bad.append(f"{f}: [model] {m}, expected replaces = {rm.get('replaces')}, "
                       f"dir = {GOMODEL_DIR!r}")
        if set(t) - {"translate", "trusted", "model", "imports", "translate_types"}:
            bad.append(f"{f}: keys {sorted(set(t))} beyond Perennial's")
    for b in bad:
        print("gomodels.py: " + b, file=sys.stderr)
    return not bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("materialize")
    m.add_argument("--perennial", default=os.environ.get("PERENNIAL_DIR"))
    c = sub.add_parser("check")
    c.add_argument("--perennial", default=os.environ.get("PERENNIAL_DIR"))
    t = sub.add_parser("test")
    t.add_argument("--perennial", default=os.environ.get("PERENNIAL_DIR"))
    t.add_argument("names", nargs="*", choices=[x[0] for x in TESTS] + [[]], default=[])
    args = ap.parse_args()
    cands = [args.perennial] if args.perennial else []
    if args.cmd == "materialize":
        print(materialize(cands))
    elif args.cmd == "check":
        if not check(cands):
            sys.exit(1)
    elif not test(cands, args.names):
        sys.exit(1)
    else:
        print("gomodels: tests ok")


if __name__ == "__main__":
    main()
