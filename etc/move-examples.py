#!/usr/bin/env python3
"""The examples' move into subdirectories by layer (`notes/examples-layout-plan.md`).

    etc/move-examples.py            move and rewrite, in a clean checkout (or on a branch made before
                                    the move: brings it across); then regenerate (printed at the end)
    etc/move-examples.py --table    print the table

What it does, in a clean working tree:

1. moves every tracked path of an example (`examples/<old>/...` and the Lean modules
   `<root>/{Code,GeneratedProof,Spec,Proof,TrustedCode,ManualProof}/github_com/mit_pdos/etcd_grove/
   examples/<old>[.lean|.toml|/...]`, in the main tree and the parts) to its new place;
2. rewrites, in every tracked text file but the append-only history (`notes/status-history.md`,
   `old/`, `third_party/`): the paths (`examples/<old>`, `etcd_grove/examples/<old>`, the Go import
   path, the dotted module and namespace path `etcd_grove.examples.<old>`, `etc/goose.py`'s
   `os.path.join` components);
3. renames, where they are meant: the Go package of a moved example (its `package` clause and its
   importers' references), the hand-written Lean namespace (`namespace`/`end`/`open` and qualified
   references, in the example's own Lean files and those importing them), and the headline
   theorems (`<prefix>_..._safe`/`_adequate`, in the example's Lean files, `etc/`, `notes/STATUS.md`,
   `CLAUDE.md`, `.claude/`);
4. fixes the relative `replace` paths of the Go modules' `go.mod`s.

The generated files (Goose translations, package initializers, `Link.lean`s) are moved with the
rest and must then be regenerated by their scripts (the commands are printed at the end). It never
commits.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# old directory, new directory (under examples/), new hand-written Lean namespace (None: the
# example has none, or keeps it), the theorem prefixes renamed to the namespace
MOVES = [
    # raft
    ("kv", "raft/kv", "raft_kv", ["kv"]),
    ("kvreconf", "raft/kvreconf", "raft_kvreconf", ["kvreconf"]),
    ("kvdurable", "raft/kvdurable", "raft_kvdurable", ["kvdurable"]),
    ("durablekv", "raft/kvfile", "raft_kvfile", ["durablekv"]),
    ("kvwitness", "raft/kvwitness", "raft_kvwitness", ["kv_witness"]),
    # etcd
    ("putget", "etcd/putget", "etcd_putget", ["putget"]),
    ("putget3", "etcd/putget3", "etcd_putget3", ["putget3"]),
    ("putgetc", "etcd/compacted", "etcd_compacted", ["putgetc"]),
    ("restart3", "etcd/restart", "etcd_restart", ["restart3"]),
    ("compactkv", "etcd/compactwatch", "etcd_compactwatch", ["compactkv"]),
    ("watchkv", "etcd/watch", "etcd_watch", ["watch"]),
    ("cachekv", "etcd/cache", "etcd_cache", ["cache"]),
    ("leasekv", "etcd/lease", "etcd_lease", ["leasekv"]),
    ("authkv", "etcd/auth", "etcd_auth", ["authkv"]),
    ("linkvtxn", "etcd/txnlin", "etcd_txnlin", ["linkvtxn"]),
    ("linkv3p", "etcd/partition", "etcd_partition", ["linkv3p"]),
    ("etcdbugs", "etcd/bugs", None, []),
    # kubernetes over etcd
    ("k8setcd3", "k8s/etcd3", "k8s_etcd3", ["k8setcd3"]),
    ("k8sdaemonset", "k8s/daemonset", "k8s_daemonset", []),
    # the shared code: namespaces kept but `common`'s, which follows its Go package
    ("common", "lib/etcdstart", "etcdstart", []),
    ("lintest", "lib/lintest", None, []),
    ("durable", "lib/durable", None, []),
    # the file-system extension's programs
    ("bboltfs", "osfs/bboltfs", "osfs_bboltfs", ["bboltfs"]),
    ("crashlog", "osfs/crashlog", "osfs_crashlog", ["crashlog", "crash"]),
]
OLD = {m[0]: m for m in MOVES}

LEAN_KINDS = ("Code", "GeneratedProof", "Spec", "Proof", "TrustedCode", "ManualProof")
LEAN_ROOTS = ("", "RaftWitness/", "PorcupineDag/")
EXPATH = "github_com/mit_pdos/etcd_grove/examples/"
# never rewritten: append-only history and vendored code
FROZEN = ("notes/status-history.md", "notes/examples-layout-plan.md", "etc/move-examples.py",
          "old/", "third_party/", ".lake/")
# rewritten later by their generators (moved, not edited)
GENERATED_KINDS = ("Code/", "GeneratedProof/")


def git(*args, out=True):
    r = subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=True)
    return r.stdout


def new_path(p):
    """The new path of a tracked path, or None if it does not move."""
    for old, new, _, _ in MOVES:
        m = re.match(r"examples/" + re.escape(old) + r"(/.*)?$", p)
        if m:
            return "examples/" + new + (m.group(1) or "")
        for lr in LEAN_ROOTS:
            for k in LEAN_KINDS:
                pre = lr + k + "/" + EXPATH
                m = re.match(re.escape(pre + old) + r"((?:\.lean|\.toml|/).*)$", p)
                if m:
                    return pre + new + m.group(1)
    return None


def go_pkg(dirpath):
    """The Go package name of the non-test files in `dirpath` (None if none)."""
    for f in sorted(os.listdir(dirpath)):
        if f.endswith(".go") and not f.endswith("_test.go"):
            m = re.search(r"^package (\w+)", open(os.path.join(dirpath, f)).read(), re.M)
            if m:
                return m.group(1)
    return None


def main():
    if "--table" in sys.argv:
        for old, new, ns, pfx in MOVES:
            print(f"examples/{old:13} -> examples/{new:20} namespace {ns or '(kept)':18} "
                  f"theorems {', '.join(p + '_*' for p in pfx) or '-'}")
        return
    if git("status", "--porcelain", "--untracked-files=no").strip():
        sys.exit("move-examples: the working tree is not clean")
    files = git("ls-files").split("\n")
    files = [f for f in files if f]

    # the Go packages before the move: old package name per moved top-level directory
    oldpkg = {}
    for old, new, _, _ in MOVES:
        d = os.path.join(ROOT, "examples", old)
        if os.path.isdir(d):
            oldpkg[old] = go_pkg(d)

    # the headline theorems: the `<prefix>_..._safe`/`_adequate` an example's own Lean files declare
    thm = {}  # old directory -> {old name: new name}
    for f in files:
        if not f.endswith(".lean"):
            continue
        for old, new, ns, pfx in MOVES:
            if not ns or not pfx or not any(
                    re.match(re.escape(lr + k + "/" + EXPATH + old) + r"(\.lean|/)", f)
                    for lr in LEAN_ROOTS for k in LEAN_KINDS):
                continue
            for name in re.findall(r"^theorem (\w+)", open(os.path.join(ROOT, f)).read(), re.M):
                for pr in pfx:
                    if re.match(re.escape(pr) + r"_\w*(safe|adequate)$", name):
                        thm.setdefault(old, {})[name] = ns + name[len(pr):]

    # 1. move
    moved = {}
    for f in files:
        n = new_path(f)
        if n:
            moved[f] = n
    for f, n in moved.items():
        os.makedirs(os.path.dirname(os.path.join(ROOT, n)), exist_ok=True)
        os.rename(os.path.join(ROOT, f), os.path.join(ROOT, n))
    for f in moved:  # empty old directories
        d = os.path.dirname(os.path.join(ROOT, f))
        while d.startswith(ROOT + os.sep) and os.path.isdir(d) and not os.listdir(d):
            os.rmdir(d)
            d = os.path.dirname(d)
    files = [moved.get(f, f) for f in files]
    newof = {v: k for k, v in moved.items()}  # new path -> old path

    def owner(f):
        """The move whose example `f` (a new path) belongs to, or None."""
        old = newof.get(f)
        if not old:
            return None
        for o, *_ in MOVES:
            if re.match(r"examples/" + re.escape(o) + r"(/|$)", old) or any(
                    re.match(re.escape(lr + k + "/" + EXPATH + o) + r"(\.lean|\.toml|/)", old)
                    for lr in LEAN_ROOTS for k in LEAN_KINDS):
                return o
        return None

    # 2.-3. rewrite
    path_rules = []
    for old, new, _, _ in MOVES:
        dotted = new.replace("/", ".")
        path_rules += [
            (re.compile(r"etcd_grove\.examples\." + re.escape(old) + r"(?![\w])"),
             "etcd_grove.examples." + dotted),
            (re.compile(r"etcd_grove/examples/" + re.escape(old) + r"(?![\w])"),
             "etcd_grove/examples/" + new),
            (re.compile(r"etcd-grove/examples/" + re.escape(old) + r"(?![\w])"),
             "etcd-grove/examples/" + new),
            (re.compile(r"(?<![\w/.-])examples/" + re.escape(old) + r"(?![\w])"),
             "examples/" + new),
            (re.compile(r'"examples",(\s*)"' + re.escape(old) + r'"'),
             '"examples",\\1' + ", ".join(f'"{c}"' for c in new.split("/"))),
        ]
    changed = 0
    for f in files:
        if f.startswith(FROZEN):
            continue
        p = os.path.join(ROOT, f)
        try:
            src = open(p, encoding="utf-8").read()
        except (UnicodeDecodeError, FileNotFoundError, IsADirectoryError):
            continue
        out = src
        generated = f.startswith(GENERATED_KINDS) or any(
            f.startswith(lr + k) for lr in LEAN_ROOTS[1:] for k in GENERATED_KINDS)
        if generated and f.endswith(".lean"):
            continue  # regenerated
        for rx, rep in path_rules:
            out = rx.sub(rep, out)
        own = owner(f)
        if f.endswith(".lean"):
            # the hand-written namespaces: in the example's files and in those importing one
            for old, new, ns, _ in MOVES:
                if not ns or ns == old:
                    continue
                imports = re.search(r"^(public )?import \S*etcd_grove\.examples\."
                                    + re.escape(new.replace("/", ".")) + r"\b", out, re.M)
                if own != old and not imports:
                    continue
                out = re.sub(r"^(namespace|end) " + re.escape(old) + r"$", r"\1 " + ns, out,
                             flags=re.M)
                out = re.sub(r"^(open[^\n]*?)(?<![\w.])" + re.escape(old) + r"(?![\w.])",
                             r"\1" + ns, out, flags=re.M)
                out = re.sub(r"(?<![\w.'«])" + re.escape(old) + r"\.(?=[A-Za-z_«])",
                             ns + ".", out)
        if f.endswith(".go"):
            # the Go package of a moved example and its importers' references
            for old, new, _, _ in MOVES:
                op, np_ = oldpkg.get(old), new.split("/")[-1]
                if not op or op == np_:
                    continue
                if own == old and os.path.dirname(f) == "examples/" + new:
                    out = re.sub(r"^package " + op + r"(_test)?$", r"package " + np_ + r"\1",
                                 out, flags=re.M)
                    out = re.sub(r"^// Package " + op + r"\b", "// Package " + np_, out,
                                 flags=re.M)
                if re.search(r'^\s*(import\s+)?"github\.com/mit-pdos/etcd-grove/examples/'
                             + re.escape(new) + r'"', out, re.M):
                    out = re.sub(r"(?<![\w.])" + op + r"\.(?=[A-Z])", np_ + ".", out)
        # the link configs' function ids, `<last directory of the spec>_<function>`
        if re.match(r"etc/(link-lean-first-[\w-]+\.txt|gen-link\.py)$", f):
            for old, new, _, _ in MOVES:
                last = new.split("/")[-1]
                if last != old:
                    out = re.sub(r"(?<![\w.])" + re.escape(old) + r"_(?=\w)", last + "_", out)
        # the headline theorems
        thm_scope = (f.endswith(".lean") or f.startswith(("etc/", ".claude/"))
                     or f in ("notes/STATUS.md", "CLAUDE.md"))
        if thm_scope:
            for old, new, ns, pfx in MOVES:
                if old not in thm:
                    continue
                if f.endswith(".lean") and own != old and not re.search(
                        r"etcd_grove\.examples\." + re.escape(new.replace("/", ".")) + r"\b", out):
                    continue
                for a, b in thm[old].items():
                    out = re.sub(r"(?<![\w.])" + re.escape(a) + r"(?!\w)", b, out)
        if out != src:
            open(p, "w", encoding="utf-8").write(out)
            changed += 1

    # 4. the go.mods' relative replaces
    for f in files:
        if not f.endswith("go.mod"):
            continue
        p = os.path.join(ROOT, f)
        new_dir = os.path.dirname(f)
        old_dir = os.path.dirname(newof.get(f, f))
        src = open(p).read()

        def fix(m):
            tgt = os.path.normpath(os.path.join(old_dir, m.group(2)))
            nt = new_path(tgt) or tgt
            for o, n, *_ in MOVES:  # a moved module directory
                if tgt == "examples/" + o or tgt.startswith("examples/" + o + "/"):
                    nt = "examples/" + n + tgt[len("examples/" + o):]
            rel = os.path.relpath(nt, new_dir)
            if not rel.startswith("."):
                rel = "./" + rel
            return m.group(1) + rel
        out = re.sub(r"(=>\s*)(\.\.?(?:/[^\s]*)?)", fix, src)
        if out != src:
            open(p, "w").write(out)

    git("add", "-A")
    print(f"move-examples: {len(moved)} files moved, {changed} rewritten. Now regenerate:")
    print("  etc/goose.py && etc/gen-init.py && (each `etc/gen-link.py --MODE > FILE` "
          "of etc/gates.sh's list) && lake build && etc/gates.sh")


if __name__ == "__main__":
    main()
