#!/usr/bin/env python3
"""The vr kit's boot tables (notes/dsv-vr.md, "Round 7", the boot; as `_swiftpaxos_boot.py`):
`Dsverify/Proof/github_com/tangledbytes/go_vsr/examples/vsrnet/BootTable.lean`, the package facts
the kit's first-run boot proofs (`examples/vsrnet/BootLinked.lean`) use, generic in the program's
table `G` (`KitG G`: `G` gives each package of `vsrnet`'s import closure its `isPkgInit`), at `G`
(`wf_*`) and at `gOff S G` (`wfO_*`, `S` a sub-list of the owned packages, whose entries are
`False`: not initialized yet), for the packages whose closure avoids the owned ones; and
`BootCmdsLinked.lean`: each command's `KitG getIsPkgInit` (`kitG`) and its boot theorem
(`wp_boot`). The owned packages are the path of encoding/json's first run on a machine: `vsrnet`
runs `replica`'s first, `replica` `network`'s, `network` encoding/json's. Generated from
etc/gen-init.py's `cmd/server1/PkgTable.lean`; run after etc/gen-init.py; `--check` exits 1 if a
file differs. (A file starting with `_`: not a kit file, etc/dsv/README.md.)"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SW = 'github_com.tangledbytes.go_vsr'
P = 'Dsverify/Proof/github_com/tangledbytes/go_vsr/examples/vsrnet'
NODES = ['orch'] + [f'client{c}' for c in range(6)] + [f'server{s}' for s in range(1, 6)]
OWNED = [f'{SW}.examples.vsrnet', f'{SW}.pkg.replica', f'{SW}.pkg.network', 'encoding.json']


def wfname(pkg):
    return pkg.replace('«', '').replace('»', '').replace('.', '_')


def table():
    """server1's chain: [(package, [children])] in order, the command itself left out."""
    txt = open(os.path.join(ROOT, P, 'cmd/server1/PkgTable.lean')).read()
    blocks = re.findall(r'  have (h\d+) : GetIsPkgInitProp pkg_id\.(\S+) \(getIsPkgInit \(GF := GF\)\) := by\n'
                        r'    refine And\.intro \?_ \?_\n    · rfl\n    exact (.*)\n', txt)
    names = {h: q for h, q, _ in blocks}
    out = []
    for h, q, ex in blocks:
        if q.startswith(f'{SW}.examples.vsrnet.cmd.'):
            continue
        out.append((q, [names[c] for c in re.findall(r'\bh\d+\b', ex)]))
    return out


HEAD = '''/-
{doc}
Generated by `etc/dsv/_vr_boot.py`; do not edit.
-/
module

{imports}

@[expose] public section

set_option linter.unusedSectionVars false
set_option maxRecDepth 100000

noncomputable section

namespace Perennial
'''


def tup(kids):
    return f'⟨{kids}True.intro⟩' if kids else 'True.intro'


def boot_table(chain):
    closure = {}
    for q, cs in chain:
        s = {q}
        for c in cs:
            s |= closure[c]
        closure[q] = s
    free = [q for q, _ in chain if not (closure[q] & set(OWNED))]
    o = [HEAD.format(doc='''The package facts of the vr kit's boot (notes/dsv-vr.md, "Round 7", the boot; as
swiftpaxos's): generic in a program's table `G` that gives every package of `vsrnet`'s import
closure its `isPkgInit` (`KitG G`), the facts at `G` (`wf_*`) and, for the packages whose closure
avoids the kit's owned packages (`ownedPkgs`: the path of encoding/json's first run, whose first
initializations the boot proves), at `gOff S G` for `S` a sub-list of `ownedPkgs` (`wfO_*`): the
table in which the packages of `S` are not initialized yet.''',
                     imports='public import Dsverify.Proof.github_com.tangledbytes.go_vsr.examples.vsrnet.Base')]
    o.append(f'namespace {SW}.examples.vsrnet\n')
    o.append('open Iris Iris.BI Iris.ProgramLogic Iris.Std\n')
    o.append('section table\nvariable [GooseExts] [GooseSemantics] [GooseInterp] [go_gctx : GoGlobalContext]\n'
             'variable {GF : BundledGFunctors} [hG : HeapGS HasLC.hasLC GF] [sem : go.Semantics]\n')
    o.append('''/-- The table `G` with the packages of `S` not initialized (their entry `False`). -/
def gOff (S : List GoString) (G : GoString → IProp GF) : GoString → IProp GF := fun p =>
  if p ∈ S then iprop(False) else G p

theorem gOff_ne (S : List GoString) (G : GoString → IProp GF) (p : GoString) (h : p ∉ S) :
    gOff S G p = G p := by
  unfold gOff; rw [if_neg h]

theorem gOff_off (S : List GoString) (G : GoString → IProp GF) (p : GoString) (h : p ∈ S) :
    gOff S G p ⊢ iprop(False) := by
  unfold gOff; rw [if_pos h]

theorem gOff_sub (S S' : List GoString) (G : GoString → IProp GF) (h : ∀ q ∈ S', q ∈ S)
    (p : GoString) : gOff S G p ⊢ gOff S' G p := by
  unfold gOff
  by_cases h' : p ∈ S'
  · rw [if_pos (h p h'), if_pos h']
  · rw [if_neg h']
    split
    · exact false_elim
    · exact .rfl

theorem gOff_le (S : List GoString) (G : GoString → IProp GF) (p : GoString) :
    gOff S G p ⊢ G p := by
  unfold gOff
  split
  · exact false_elim
  · exact .rfl

theorem gOff_nil (G : GoString → IProp GF) : gOff [] G = G := by
  funext p; unfold gOff; simp
''')
    o.append('/-- The kit\'s owned packages (the file header). -/\ndef ownedPkgs : List GoString :=\n  [' +
             ', '.join(f'pkg_id.{q}' for q in OWNED) + ']\n')
    o.append('/-- A program\'s table gives every package of `vsrnet`\'s import closure its fact. -/\n'
             'structure KitG (G : GoString → IProp GF) : Prop where')
    for q, _ in chain:
        o.append(f'  e_{wfname(q)} : G pkg_id.{q} = isPkgInit (PROP := IProp GF) pkg_id.{q}')
    o.append('')
    for q, cs in chain:
        kids = ''.join(f'wf_{wfname(c)} h, ' for c in cs)
        o.append(f'theorem wf_{wfname(q)} {{G : GoString → IProp GF}} (h : KitG G) :\n'
                 f'    GetIsPkgInitProp pkg_id.{q} G :=\n'
                 f'  And.intro h.e_{wfname(q)} {tup(kids)}\n')
    for q, cs in chain:
        if q not in free:
            continue
        kids = ''.join(f'wfO_{wfname(c)} h S hS, ' for c in cs)
        o.append(f'theorem wfO_{wfname(q)} {{G : GoString → IProp GF}} (h : KitG G) (S : List GoString)\n'
                 f'    (hS : ∀ q ∈ S, q ∈ ownedPkgs) : GetIsPkgInitProp pkg_id.{q} (gOff S G) :=\n'
                 f'  And.intro ((gOff_ne S G _ (fun hm => (by decide : pkg_id.{q} ∉ ownedPkgs) (hS _ hm))).trans\n'
                 f'    h.e_{wfname(q)}) {tup(kids)}\n')
    o.append('end table\n')
    o.append(f'end {SW}.examples.vsrnet\nend Perennial\n')
    return '\n'.join(o)


CMD = """namespace {SW}.examples.vsrnet.cmd.{n}

section boot
variable [GooseExts] [GooseSemantics] [GooseInterp] [go_gctx : GoGlobalContext]
variable {{GF : BundledGFunctors}} [hG : HeapGS HasLC.hasLC GF] [sem : go.Semantics]
variable [package_sem : cmd.{n}.Assumptions]

theorem kitG : KitG (getIsPkgInit (GF := GF)) := by
  constructor <;> rfl

set_option maxHeartbeats 4000000 in
/-- **Command `{n}`'s boot**: its initialization from the machine's empty package state, through
`vsrnet`'s first one, returns encoding/json's fresh registry (`codecFresh`). -/
theorem wp_boot :
    {{{{ ownGoState (hG := hG.goose_localGS.goose_go_stateGS) ∅ }}}}
      (App (Val initialize') (Val #()))
    {{{{ RET #(); ownInitializing (getIsPkgInit (GF := GF)) ∗
        isPkgInit (PROP := IProp GF) pkg_id.{SW}.examples.vsrnet.cmd.{n} ∗
        encoding.json.codecFresh (GF := GF) }}}} := by
  wp_start as Hgs
  ihave Hown := ownInitializing_of_empty
    (gOff (pkg_id.{SW}.examples.vsrnet.cmd.{n} :: bootS1) (getIsPkgInit (GF := GF))) $$ Hgs
  iapply wp_package_init_first (pkg_id.{SW}.examples.vsrnet.cmd.{n})
    (P := isPkgInit (PROP := IProp GF) pkg_id.{SW}.examples.vsrnet.cmd.{n})
    (Q := encoding.json.codecFresh (GF := GF))
    (gA := gOff (pkg_id.{SW}.examples.vsrnet.cmd.{n} :: bootS1) (getIsPkgInit (GF := GF)))
    (gB := gOff bootS1 (getIsPkgInit (GF := GF))) (gC := getIsPkgInit (GF := GF))
    (hA := gOff_off _ _ _ (by decide)) (hAB := gOff_sub _ _ _ (by decide)) (heq := rfl) $$ [Hown] HΦ
  iframe Hown
  iintro Hown
  try wp_auto
  wp_apply boot_vsrnet kitG $$ Hown as ⟨Hown, #Hd, HR⟩
  try wp_auto
  iframe Hown HR
  isplitr
  · ipureintro; exact isPanic_intoVal ()
  is_pkg_init_finish

end boot

end {SW}.examples.vsrnet.cmd.{n}
"""


def boot_cmds():
    o = [HEAD.format(doc='''The vr kit's twelve commands' boots (notes/dsv-vr.md, "Round 7", the boot): each command's
initialization from the machine's empty package state, its first, through `vsrnet`'s
(`BootLinked.lean`, `boot_vsrnet`), at the command's table (`getIsPkgInit`, its `PkgTable.lean`;
`kitG`), returning encoding/json's fresh registry (`codecFresh`).''',
                     imports='\n'.join(f'public import Dsverify.Proof.{SW}.examples.vsrnet.cmd.{n}.PkgTable'
                                       for n in NODES) +
                     f'\npublic import Dsverify.Proof.{SW}.examples.vsrnet.BootLinked')]
    o.append('open Iris Iris.BI Iris.ProgramLogic Iris.Std Iris.ProofMode')
    o.append(f'open {SW} {SW}.examples.vsrnet')
    o.append('open github_com.imdea_software.swiftpaxos (wp_package_init_first)\n')
    for n in NODES:
        o.append(CMD.format(SW=SW, n=n))
    o.append('end Perennial\n')
    return '\n'.join(o)


def main():
    chain = table()
    files = {os.path.join(P, 'BootTable.lean'): boot_table(chain),
             os.path.join(P, 'BootCmdsLinked.lean'): boot_cmds()}
    bad = False
    for f, txt in files.items():
        path = os.path.join(ROOT, f)
        if '--check' in sys.argv:
            if not os.path.exists(path) or open(path).read() != txt:
                print(f'differs: {f}')
                bad = True
        else:
            open(path, 'w').write(txt)
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
