def find_class(c):
    """Where premise class `c` (`a.b.Cls`, maybe applied: `a.NoSignals a.quietSigs`; a Lean name
    under `Perennial`) is declared: (file, line, the declaration's line count with its doc comment
    and its fields), or None."""
    c = c.split()[0]
    parts = c.split('.')
    name, ns = parts[-1], parts[:-1]
    r = subprocess.run(['git', 'grep', '-n', '-E',
                        rf'^(class|structure|def|abbrev) ({re.escape(".".join(ns))}\.)?{re.escape(name)}\b',
                        '--', 'Dsverify/*.lean', 'Net/*.lean', 'Proof/*.lean', 'Spec/*.lean'],
                       cwd=ROOT, capture_output=True, text=True)
    hits = [h.split(':', 2) for h in r.stdout.splitlines()]
    pre = '/'.join(ns)
    best = [h for h in hits if f' {c}' in h[2]] or [h for h in hits if pre and f'/{pre}/' in '/' + h[0]]
    if not best:
        return None
    f, ln = best[0][0], int(best[0][1])
    src = open(os.path.join(ROOT, f)).read().split('\n')
    s = ln - 1  # back over its doc comment
    while s > 0 and src[s - 1].strip() and not src[s - 1].startswith(('end ', 'variable', 'section', 'namespace')):
        s -= 1
    e = ln  # forward over its continuation lines and fields (indented or blank, up to the next declaration)
    while e < len(src) and (not src[e].strip() or src[e].startswith((' ', '\t'))):
        e += 1
    while e > ln and not src[e - 1].strip():
        e -= 1
    return f, ln, e - s


def audit(kit, kg):
    st = kg['statement']
    spec = os.path.join('Dsverify', 'Spec', pkg_path(kg), 'TopLevelRobustness.lean')
    n = len(open(os.path.join(ROOT, spec)).read().split('\n')) - 1
    print(f'kitgen --audit {kit}: what a reader of `{st["theorem"]}.spec` checks\n')
    print(f'  {n:5d}  {spec}  (the statement; generated from etc/dsv/{kit}.py, committed)')
    defs = os.path.join('Dsverify', 'Proof', pkg_path(kg), 'TopLevelDefs.lean')
    if os.path.exists(os.path.join(ROOT, defs)):
        nd = len(open(os.path.join(ROOT, defs)).read().split('\n')) - 1
        print(f'  {nd:5d}  {defs}  (the definitions it names: boot, system, the addresses)')
    else:
        nd = 0
    total = n + nd
    cls = [c for _, _, cs in premises(st) for c in cs]
    if cls:
        print(f'\n  the premise classes ({len(cls)}):')
    for c in cls:
        w = find_class(c)
        if w is None:
            print(f'      ?  {c}  (declaration not found: read it by hand)')
        else:
            f, ln, k = w
            total += k
            print(f'  {k:5d}  {c}  ({f}:{ln})')
    if not cls:
        print('\n  no premise classes: the statement rests on its definitions alone')
    print(f'\n  {total:5d}  lines in all (the definitions they name in turn are not counted)')


