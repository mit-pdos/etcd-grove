GO_MAIN = '''// Command {n} is {doc} (package {gopkg}).
package main

import "{imp}"

func main() {{
\t{gopkg}.{call}
}}
'''


def go_mains(kit, kg):
    out = {}
    d = os.path.join(kg['go_module_dir'], kg['go_pkg_dir'], 'cmd')
    for m in machines(kg):
        txt = GO_MAIN.format(n=m.n, doc=role_get(m, 'go_doc'), gopkg=kg['go_pkg'],
                             imp=kg['go_import'], call=role_get(m, 'go_call'))
        out[os.path.join(d, m.n, 'main.go')] = go_header(kit) + txt
    return out


def go_consts(kit, kg):
    """`kit_gen.go`: the kit's constants and address functions (`go_consts`)."""
    gc = kg.get('go_consts')
    if not gc:
        return {}
    o = [go_header(kit), f'package {kg["go_pkg"]}\n']
    consts = gc.get('consts', [])
    if consts:
        o.append('\n// The kit\'s configuration (etc/dsv/%s.py).\nconst (\n' % kit)
        w = max(len(c[0]) for c in consts)
        for name, typ, val, cdoc in consts:
            if cdoc:
                o.append(f'\t// {cdoc}\n')
            o.append(f'\t{name.ljust(w)} {typ} = {val}\n')
        o.append(')\n')
    for fn, spec in gc.get('addrs', {}).items():
        if isinstance(spec, dict):
            addrs = [f'{spec.get("host", "127.0.0.1")}:{spec["base"] + j}' for j in range(spec['count'])]
            fdoc = spec.get('doc', f'{fn} is the kit\'s addresses.')
        else:
            fdoc, addrs = spec
        o.append(f'\n// {fdoc}\nfunc {fn}() []string {{\n\treturn []string{{\n')
        o.extend(f'\t\t"{a}",\n' for a in addrs)
        o.append('\t}\n}\n')
    return {os.path.join(kg['go_module_dir'], kg['go_pkg_dir'], 'kit_gen.go'): ''.join(o)}


def run_codecs(kg, check):
    """Call the codec generators (never re-implemented here); returns the failures."""
    bad = []
    for kind, toml, outdir, pkg, *extra in kg.get('codecs', []):
        flags = list(extra[0]) if extra else []
        cmd = [sys.executable, os.path.join(ROOT, CODEC_GEN[kind]), toml, outdir, '--pkg', pkg] + flags
        if check:
            cmd.append('--check')
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            bad.append(f'{CODEC_GEN[kind]} {toml}: exit {r.returncode}\n{r.stdout}{r.stderr}')
    return bad


