BOOT_DEF = '''/-- The boot program of a command: run its package's initializer `init`, then call its `main`. -/
def boot [GoGlobalContext] (init : val) (main : GoString) : Expr :=
  Seq (App (Val init) (Val #()))
    (App (App (Val (GoInstruction (FuncResolve main []))) (Val #())) (Val #()))
'''


def defs_file(kit, kg):
    d, pkg = kg['defs'], kg['lean_pkg']
    ms = machines(kg)
    o = [lean_header(kit), doc(d['doc']), 'module\n\n',
         'public import GooseLang.Ext.Net.Adequacy\npublic import GooseLang.Ext.Net.Deploy\n']
    o.extend(f'public import Dsverify.Proof.{pkg}.cmd.{m.n}.Base\n' for m in ms)
    o.append(lines(d.get('imports')))
    o.append('\n@[expose] public section\n\nnoncomputable section\n\n')
    o.append(lines(d.get('options', ['set_option linter.iris.style.nameCheck false'])))
    if d.get('options', True):
        o.append('\n')
    o.append('namespace Perennial\n\nopen Iris Iris.BI Net\n\n')
    o.append(f'namespace {pkg}\n\n')
    o.append(INSTANCES + '\n' + BOOT_DEF + '\n')
    o.append(f'/-- {d["system_doc"].strip()} -/\n')
    o.append('def system [GoGlobalContext] (σ : Nat → state) : List (Expr × state) :=\n')
    ents = [f'(boot cmd.{m.n}.initialize\' cmd.{m.n}.main, σ {m.i})' for m in ms]
    if d.get('system_layout', 'line') == 'line':
        o.append('  [' + ', '.join(ents) + ']\n')
    else:
        o.append('  [' + ',\n   '.join(ents) + ']\n')
    o.append('\n' + lines(d['addrs_def']) + '\n')
    o.append(f'end {pkg}\nend Perennial\n')
    return ''.join(o)


