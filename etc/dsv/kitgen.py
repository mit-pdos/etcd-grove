INSTANCES = 'attribute [local instance] netExts netExtsSemantics netExtsInterp netExts_hasNet\n'

HEAP_AT = '''abbrev heapAt [lctx : GoLocalContext] (G : GooseGlobalGS HasLC.hasLC remoteGF)
    (L : GooseLocalGS remoteGF) : HeapGS HasLC.hasLC remoteGF :=
  ⟨G, { L with goose_go_local_context := lctx }⟩
'''


def heap_at(text):
    return f'/-- {text.strip()} -/\n' + HEAP_AT


def premises(st):
    """The statement's premises: [(binder name, text, [classes])]. An entry `(name, cls)` is a
    heap premise `(∀ G L, letI := heapAt G L; cls remoteGF) →`; `(name, dict(raw=..., classes=[]))`
    is copied (its lines indented as written)."""
    out = []
    for name, p in st.get('premises', []):
        if isinstance(p, str):
            out.append((name, f'    (∀ G L, letI := heapAt G L; {p} remoteGF) →\n', [p]))
        else:
            out.append((name, lines(p['raw']), p.get('classes', [])))
    return out


def spec_file(kit, kg):
    st, pkg = kg['statement'], kg['lean_pkg']
    ms = machines(kg)
    o = [lean_header(kit), doc(st['doc']), 'module\n\n']
    o.append(f'public import Dsverify.Proof.{pkg}.TopLevelDefs\n')
    o.append(lines(st.get('imports')))
    o.append('\n@[expose] public section\n\nnoncomputable section\n\n'
             'set_option linter.iris.style.nameCheck false\n\nnamespace Perennial\n\n'
             'open Iris Iris.BI Net\n\n')
    o.append(f'namespace {pkg}\n\n')
    if st.get('opens'):
        o.append(lines(st['opens']) + '\n')
    o.append(INSTANCES + '\n')
    if st.get('heap_at') == 'spec':
        o.append(heap_at(st['heap_at_doc']) + '\n')
    o.append(f'/-- See the file header. -/\ndef {st["theorem"]}.spec : Prop :=\n')
    o.append('  ∀ [GoGlobalContext] [lctx : GoLocalContext] [sem : go.Semantics]\n')
    for m in ms:
        o.append(f'    [{m.n}_sem : cmd.{m.n}.Assumptions]\n')
    ps = premises(st)
    if ps:
        o.append('    [field_sem : net.FieldAssumptions] [go.BasicIntoValInj],\n')
        o.extend(t for _, t, _ in ps)
        o.append('    ∀ (σ : Nat → state) (g : GlobalState) (threads : Nat),\n')
    else:
        o.append('    [field_sem : net.FieldAssumptions] [go.BasicIntoValInj]\n')
        o.append('    (σ : Nat → state) (g : GlobalState) (threads : Nat),\n')
    o.append(f'    DistDeploy {st["addrs"]} (system σ) g →\n')
    o.append(f'    Robustness.Robust [] (system σ) g threads ({st["steps"]})\n\n')
    o.append(f'end {pkg}\nend Perennial\n')
    return ''.join(o)


