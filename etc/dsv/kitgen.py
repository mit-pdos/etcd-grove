def mains_file(kit, kg):
    mn, pkg = kg['mains'], kg['lean_pkg']
    ms = machines(kg)
    o = [lean_header(kit), doc(mn['doc']), 'module\n\n']
    o.extend(f'public import Dsverify.Proof.{pkg}.cmd.{m.n}.Base\n' for m in ms)
