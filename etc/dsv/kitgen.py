    o.append('\n@[expose] public section\n\n')
    o.append(lines(mn.get('options', ['set_option linter.iris.style.nameCheck false',
                                      'set_option linter.unusedSectionVars false'])))
    o.append('\nnoncomputable section\n\nnamespace Perennial\n\n')
    o.append(lines(mn['opens']) + '\n')
    for m in ms:
        o.append(f'namespace {pkg}.cmd.{m.n}\n\nsection proof\n')
        o.append(lines(sub(mn['variables'], m)) + '\n')
