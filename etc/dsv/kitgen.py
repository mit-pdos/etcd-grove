def generated(kit, kg):
    out = {}
    pp = pkg_path(kg)
    if 'roles' in kg and kg.get('go_mains', True):
        out.update(go_mains(kit, kg))
    out.update(go_consts(kit, kg))
    if 'statement' in kg and kg['statement'].get('generate', True):
        out[os.path.join('Dsverify', 'Spec', pp, 'TopLevelRobustness.lean')] = spec_file(kit, kg)
    if 'defs' in kg:
        out[os.path.join('Dsverify', 'Proof', pp, 'TopLevelDefs.lean')] = defs_file(kit, kg)
    if 'proof' in kg:
        out[os.path.join('Dsverify', 'Proof', pp, 'TopLevelRobustness.lean')] = proof_file(kit, kg)
    if 'mains' in kg:
        out[os.path.join('Dsverify', 'Proof', pp, 'Mains.lean')] = mains_file(kit, kg)
    if 'boot' in kg:
        out[os.path.join('Dsverify', 'Proof', pp, 'BootTable.lean')] = boot_table_file(kit, kg)
        out[os.path.join('Dsverify', 'Proof', pp, 'BootCmdsLinked.lean')] = boot_cmds_file(kit, kg)
    return out


def find_class(c):
    """Where premise class `c` (`a.b.Cls`, Lean name under `Perennial`) is declared: (file, line,
    line count of the declaration up to the next blank line), or None."""
    parts = c.split('.')
    name, ns = parts[-1], parts[:-1]
    cands = []
    for top in ('Dsverify', 'Net', ''):
        d = os.path.join(ROOT, top, 'Proof', *ns) if top else os.path.join(ROOT, 'Proof', *ns)
        if os.path.isdir(d):
            cands += [os.path.join(d, f) for f in sorted(os.listdir(d)) if f.endswith('.lean')]
    r = subprocess.run(['git', 'grep', '-n', '-E', rf'^(class|structure|def|abbrev) {re.escape(name)}\b',
                        '--', 'Dsverify/*.lean', 'Net/*.lean'], cwd=ROOT, capture_output=True, text=True)
    hits = [h.split(':', 2) for h in r.stdout.splitlines()]
    pre = '/'.join(ns)
    best = [h for h in hits if pre and f'/{pre}/' in '/' + h[0]] or [h for h in hits if h[0] in
                                                                     [os.path.relpath(x, ROOT) for x in cands]]
    if not best:
        return None
    f, ln = best[0][0], int(best[0][1])
    src = open(os.path.join(ROOT, f)).read().split('\n')
    # the declaration with its doc comment: back to the doc's start, forward to a blank line
    s = ln - 1
    while s > 0 and src[s - 1].strip() and not src[s - 1].startswith('end '):
        s -= 1
    e = ln - 1
    while e < len(src) and src[e].strip():
        e += 1
    return f, ln, e - s


def audit(kit, kg):
    st = kg['statement']
    spec = os.path.join('Dsverify', 'Spec', pkg_path(kg), 'TopLevelRobustness.lean')
    n = len(open(os.path.join(ROOT, spec)).read().split('\n')) - 1
    print(f'kitgen --audit {kit}: what a reader of `{st["theorem"]}.spec` checks\n')
    print(f'  {n:5d}  {spec}  (the statement; generated from etc/dsv/{kit}.py, committed)')
    defs = os.path.join('Dsverify', 'Proof', pkg_path(kg), 'TopLevelDefs.lean')
    if os.path.exists(os.path.join(ROOT, defs)):
        nd = len(open(os.path.join(ROOT, defs)).read().split('\n')) - 1
        print(f'  {nd:5d}  {defs}  (the definitions it names: boot, system, the addresses)')
    else:
        nd = 0
    total = n + nd
    cls = [c for _, _, cs in premises(st) for c in cs]
    if cls:
        print(f'\n  the premise classes ({len(cls)}):')
    for c in cls:
        w = find_class(c)
        if w is None:
            print(f'      ?  {c}  (declaration not found: read it by hand)')
        else:
            f, ln, k = w
            total += k
            print(f'  {k:5d}  {c}  ({f}:{ln})')
    if not cls:
        print('\n  no premise classes: the statement rests on its definitions alone')
    print(f'\n  {total:5d}  lines in all (the definitions they name in turn are not counted)')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('kits', nargs='*')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--audit', action='store_true')
    ap.add_argument('--scaffold', action='store_true')
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--no-codecs', action='store_true')
    a = ap.parse_args()
    kits = load_kits()
    for k in a.kits:
        if k not in kits:
            sys.exit(f'kitgen: no KITGEN in etc/dsv/{k}.py')
    names = a.kits or sorted(kits)
    if a.audit:
        for k in names:
            audit(k, kits[k])
        return
    if a.scaffold:
        for k in names:
            for f, txt in {**start_scaffold(k, kits[k]), **nonvacuity_scaffold(k, kits[k])}.items():
                p = os.path.join(ROOT, f)
                if os.path.exists(p):
                    print(f'kitgen: {f} exists; left as it is')
                else:
                    os.makedirs(os.path.dirname(p), exist_ok=True)
                    open(p, 'w').write(txt)
                    print(f'kitgen: wrote the scaffold {f}')
        return
    bad, nfiles = [], 0
    for k in names:
        files = generated(k, kits[k])
        for f, txt in sorted(files.items()):
            nfiles += 1
            p = os.path.join(ROOT, f)
            if a.list:
                print(f)
            elif a.check:
                if not os.path.exists(p) or open(p).read() != txt:
                    bad.append(f'differs: {f}')
            else:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                if not os.path.exists(p) or open(p).read() != txt:
                    open(p, 'w').write(txt)
                    print(f'kitgen: wrote {f}')
        if not a.list and not a.no_codecs:
            bad += run_codecs(kits[k], a.check)
    if a.list:
        return
    for b in bad:
        print(f'kitgen: {b}')
    if bad:
        print(f'kitgen: FAILED ({len(bad)} failures, {nfiles} generated files and the codecs; run {ME})')
        sys.exit(1)
    print(f'kitgen: ok ({len(names)} kits, {nfiles} files{" up to date" if a.check else ""})')


if __name__ == '__main__':
    main()
