PLAIN_DOC = '''/-- A command's boot program, from its initializer's spec (with the program's package table
`getIs`) and a spec of its `main` with precondition `P` ({src}). -/
'''


def boot_section(pr):
    v = pr.get('boot', 'plain')
    o = ['section boot\nvariable [GoGlobalContext] {GF : BundledGFunctors}\n\n']
    if v == 'plain':
        o.append(PLAIN_DOC.replace('{src}', pr.get('boot_src', "remote's counter's `wp_boot`")))
        o.append(WP_BOOT_PLAIN)
    else:
        o.append(WP_BOOT_GOSTATE.replace('{doc}', pr['boot_doc'].rstrip()))
    o.append('\nend boot\n')
    return ''.join(o)


def proof_file(kit, kg):
    pr, st, pkg = kg['proof'], kg['statement'], kg['lean_pkg']
    ms = machines(kg)
    thm = st['theorem']
    o = [lean_header(kit), doc(pr['doc']), 'module\n\n']
    o.append(f'public import Dsverify.Spec.{pkg}.TopLevelRobustness\n')
    o.append(lines(pr.get('imports')))
    o.extend(f'public import Dsverify.Proof.{pkg}.cmd.{m.n}.PkgTable\n' for m in ms)
    o.extend(f'public import Dsverify.Proof.{pkg}.cmd.{m.n}.Init\n' for m in ms)
    o.append('\n@[expose] public section\n\n')
    o.append(lines(pr.get('options', ['set_option linter.iris.style.nameCheck false',
                                      'set_option linter.unusedSectionVars false',
                                      'set_option maxRecDepth 100000'])))
    o.append('\nnoncomputable section\n\nnamespace Perennial\n\n'
             'open Iris Iris.BI Iris.ProgramLogic Iris.Std Iris.ProofMode Net Robustness\n\n')
    o.append(f'namespace {pkg}\n\n')
    o.append(lines(pr.get('opens')) + '\n')
    o.append(INSTANCES + '  GooseGlobalGS.gooseInvGS\n\n')
    o.append(boot_section(pr) + '\n')
    # the theorem
    head = pr.get('head', f'/-- **The {kg.get("title", kit)} kit, closed** (see the statement\'s file). -/\n'
                          f'theorem {thm} : {thm}.spec := by')
    o.append(lines(head))
    ss = ' '.join(f's{m.i}' for m in ms)
    names = [n for n, _, _ in premises(st)]
    if names:
        o.append(f'  intro gctx lctx sem {ss} fsem bvi\n    {" ".join(names)} σ g threads\n')
    else:
        o.append(f'  intro gctx lctx sem {ss} fsem bvi σ g threads\n')
    o.append(lines(pr.get('bridge', f'  refine robust_of_distProtoRB (GF := remoteGF) {st["addrs"]} '
                                     f'(system σ) g threads ({st["steps"]}) ?_\n  intro G π hrb')))
    o.append(lines(pr['start']))
    o.append('  imodintro\n')
    for j, m in enumerate(ms):
        share = role_get(m, 'share')
        o.append(f'  iexists fun i => if i = 0 then iprop({share})\n' if j == 0 else
                 f'      else if i = {m.i} then iprop({share})\n')
    o.append('      else iprop(True)\n')
    o.append('''  isplitr
  · ipureintro
    intro i m hm hG hGG hctx
    obtain ⟨G', ⟨Lexts, Llctx, Lheap, Lgs, Lthr, Lcr⟩⟩ := hG
    dsimp only at hGG hctx
    subst hGG hctx
    letI hG : HeapGS .hasLC remoteGF := ⟨G', ⟨Lexts, Llctx, Lheap, Lgs, Lthr, Lcr⟩⟩
''')
    if 'have' in pr:
        o.append(lines(pr['have']))
    else:
        for n, t, cls in premises(st):
            if t.startswith('    (∀ G L, letI := heapAt G L; '):
                o.append(f'    haveI : {cls[0]} remoteGF := {n} G\' hG.goose_localGS\n')
    o.append('    match i, hm with\n')
    for m in ms:
        frame = role_get(m, 'frame')
        o.append(f'''    | {m.i}, hm =>
      cases hm
      dsimp only
      simp only [Nat.reduceEqDiff, ↓reduceIte]
      iintro {role_get(m, 'intro')} Hgs
      iapply wp_boot cmd.{m.n}.initialize' cmd.{m.n}.main _ cmd.{m.n}.getIsPkgInit
          (cmd.{m.n}.wp_initialize' _ cmd.{m.n}.getIsPkgInit_wf) _
          ({role_get(m, 'main')}) $$ [{frame}] Hgs
      iframe #
''')
        if frame:
            o.append(f'      iframe {frame}\n')
    o.append('  · simp only [system]\n')
    for m in ms:
        sp = role_get(m, 'split')
        o.append(f'    iapply BigSepL.bigSepL_cons.2\n    isplitl [{sp}]\n'
                 f'    · simp only [Nat.zero_add, Nat.reduceAdd, Nat.reduceEqDiff, ↓reduceIte]\n')
        pre = role_get(m, 'split_pre')
        if pre:
            o.append(''.join(f'      {x}\n' for x in pre.split('\n')))
        o.append('      iframe #\n')
        if sp:
            o.append(f'      iframe {sp}\n')
    o.append('    iapply BigSepL.bigSepL_nil.2\n    iempintro\n\n')
    if pr.get('tail'):
        o.append(lines(pr['tail']) + '\n')
    o.append(f'#print axioms {pr.get("axioms_of", thm)}\n\n')
    o.append(f'end {pkg}\nend Perennial\n')
    return ''.join(o)


