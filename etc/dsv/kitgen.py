#!/usr/bin/env python3
"""kitgen: a dsverify kit's generated plumbing, from the `KITGEN` section of its kit file
`etc/dsv/<kit>.py` (notes/dsv-kitgen.md; etc/dsv/README.md, "Adding a kit").

Usage:
  etc/dsv/kitgen.py [KIT ...]              write the generated files (default: every kit with KITGEN)
  etc/dsv/kitgen.py --check [KIT ...]      write nothing; exit 1 if a generated file differs
  etc/dsv/kitgen.py --audit KIT            print what a reader of the kit's statement must check
  etc/dsv/kitgen.py --scaffold KIT         write the hand-written files' starting points, if absent
  etc/dsv/kitgen.py --list [KIT ...]       print the generated files
  etc/dsv/kitgen.py --export-challenge DIR KIT   the kit as a challenge for a proving run (none of
                                           its proofs; --no-skill, --skill-from REV, --code-changes),
                                           the lab's files in DIR.lab; then the leak check
  etc/dsv/kitgen.py --leak-check DIR KIT   the leak check of an exported tree
  --no-codecs                              do not run the codec generators (they run Go)

Generated, committed, and checked by `--check` in etc/gates.sh (each file carries a header naming
this script and the kit file):
  Go    examples/.../<kitpkg>/cmd/<n>/main.go    every machine's command
        examples/.../<kitpkg>/kit_gen.go         the constants and addresses (`go_consts`)
        the codecs, by their generators (models/net/rpc/rpcgen.py, models/json/jsongen.py,
        models/protobuf/pbgen.py; `--check` is passed through)
  Lean  Dsverify/Spec/<pkg>/TopLevelRobustness.lean   the statement (`statement`)
        Dsverify/Proof/<pkg>/TopLevelDefs.lean        boot, system, addresses (`defs`)
        Dsverify/Proof/<pkg>/TopLevelRobustness.lean  the statement's proof (`proof`)
        Dsverify/Proof/<pkg>/Mains.lean               every command's `wp_main` (`mains`)
        Dsverify/Proof/<pkg>/BootTable.lean, BootCmdsLinked.lean   a first-run boot (`boot`)

This script is untrusted: a reader audits the files it writes (`--audit`), never the script. It is
not a kit file (etc/goose.py's `dsv_kits` skips it).
"""
