# The kits and their machines

def load_kits():
    """The kit files `etc/dsv/*.py` with a `KITGEN` section, by name (as goose.dsv_kits loads
    them: name order, files starting with `_` and this script skipped)."""
    out = {}
    for f in sorted(os.listdir(DSV)):
        if not f.endswith('.py') or f.startswith('_') or f == 'kitgen.py':
            continue
        spec = importlib.util.spec_from_file_location('kitgen_kit_' + f[:-3], os.path.join(DSV, f))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        if hasattr(m, 'KITGEN'):
            out[f[:-3]] = m.KITGEN
    return out


class Machine:
    """One machine of the deployment: its command `n`, Go id `id` (None for the orchestrator),
    index `i` in `system`, index `k` within its role, and its role's configuration."""

    def __init__(self, role, ident, i, k, pkg):
        self.role, self.id, self.i, self.k, self.pkg = role, ident, i, k, pkg
        self.n = role['cmd']
        self.n = sub(role['cmd'], self) if '{' in role['cmd'] else role['cmd']


def machines(kg):
    out, i = [], 0
    for role in kg['roles']:
        for k, ident in enumerate(role.get('ids', [None])):
            out.append(Machine(role, ident, i, k, kg['lean_pkg']))
            i += 1
    return out


_TOK = re.compile(r'\{(n|id|i|k|pkg|name|title)\}')


def sub(t, m=None, kg=None):
    """Template `t` at machine `m`: a function of the machine, or a string whose `{n}`, `{id}`,
    `{i}`, `{k}`, `{pkg}` (and `{name}`, `{title}` of the kit) are replaced; nothing else of the
    text is touched (Lean's braces stay)."""
    if callable(t):
        return t(m)
    vals = {}
    if m is not None:
        vals = dict(n=m.n, id=str(m.id), i=str(m.i), k=str(m.k), pkg=m.pkg)
    if kg is not None:
        vals.update(pkg=kg['lean_pkg'], name=kg['name'], title=kg.get('title', kg['name']))
    return _TOK.sub(lambda mt: vals.get(mt.group(1), mt.group(0)), t)


def role_get(m, key, default=''):
    v = m.role.get(key, default)
    return sub(v, m)


def lean_header(kit):
    return f'-- Generated by {ME} from etc/dsv/{kit}.py; do not edit.\n'


def go_header(kit):
    """A generated Go file's header line, which goes LAST: goose's translation records Go source
    positions (`/-- go: main.go:6:6 -/`), so a first line would change the translation of every
    retrofitted command."""
    return f'\n// Code generated by {ME} from etc/dsv/{kit}.py; DO NOT EDIT.\n'


def pkg_path(kg):
    return kg['lean_pkg'].replace('.', '/')


def lines(xs):
    """A list of lines (or one string) as text ending in a newline, or ''."""
    if not xs:
        return ''
    if isinstance(xs, str):
        return xs if xs.endswith('\n') else xs + '\n'
    return ''.join(x + '\n' for x in xs)


def doc(text):
    return f'/-\n{text.rstrip()}\n-/\n'


