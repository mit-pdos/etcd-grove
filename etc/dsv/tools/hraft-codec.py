def fk(kind, i, t):
    a = f'a{i}'
    if kind == 'u64':
        return dict(T='w64', f=f'fU64 {a}', zero=f'{a} = W64 0', body=f'u64Le {a}', E=f'getU64_enc {a} _',
                    L=f'wp_rpcDec_{t}', O=None, ztac=None, split='by_cases')
    if kind == 'u8':
        return dict(T='w8', f=f'fU8 {a}', zero=f'{a} = W8 0', body=f'u64Le (W64 (uint.Z {a}))', E=f'decU8_enc {a} _',
                    L=f'wp_rpcDec_{t}', O=None, ztac=None, split='by_cases')
    if kind == 'bool':
        return dict(T='Bool', f=f'fBool {a}', zero=f'{a} = false', body=f'encBool {a}', E='decBool_enc _ _',
                    L=f'wp_rpcDec_{t}', O=None, ztac=None, split='by_cases')
    if kind == 'str':
        return dict(T='GoString', f=f'fStr {a}', zero=f'{a} = []', body=f'rpctransport.encStr {a}',
                    E=f'getTag_encStr {a} _ {SIDE}', L=f'wp_rpcDec_{t}', O=None, ztac=None, split='by_cases')
    if kind == 'bytes':
        return dict(T='List w8', f=f'fBytes {a}', zero=f'{a} = []', body=f'encBytes {a}',
                    E=f'decBytes_enc {a} _ {SIDE}', L=f'wp_rpcDec_{t}', O='bytesO', ztac='bytesO_zero', split='by_cases')
    if kind == 'ents':
        return dict(T='List EntV', f=f'fEnts {a}', zero=f'{a} = []',
                    body=f'(encU64 (W64 {a}.length) ++ ({a}.map encEnt).flatten)',
                    E=f'decEnts_enc {a} _ {SIDE}', L=f'wp_rpcDec_{t}', O='entsO', ztac='entsO_zero', split='by_cases')
    if kind == 'hdr':
        return dict(T='HdrV', f=f'fStruct (encHdr {a})', zero=None, body=f'encHdr {a}',
                    E=f'decHeaderV_enc {a} _ {SIDE}', L=f'wp_rpcDec_{t}', O='hdrO', ztac=None, split=None)
    raise Exception(kind)

def nest(fs, last='rest'):
    s = last
    for f in reversed(fs):
        s = f'({f} ++ {s})'
    return s

