# kind -> (decoder lemma tN given, pure decoder, value type, O form ('pt' plain points-to | name of O), zero tactic)
def kinfo(kind, t):
    if kind == 'u64': return dict(D='getU64', T='w64', O=None, zero='skip', z='(W64 0)')
    if kind == 'u8': return dict(D='decU8', T='w8', O=None, zero='skip', z='(W8 0)')
    if kind == 'bool': return dict(D='decBool', T='Bool', O=None, zero='skip', z='false')
    if kind == 'str': return dict(D='getTag', T='GoString', O=None, zero='skip', z='([] : GoString)')
    if kind == 'bytes': return dict(D='decBytes', T='List w8', O='bytesO', zero='bytesO_zero', z='slice.nil')
    if kind == 'hdr': return dict(D='decHeaderV', T='HdrV', O='hdrO', zero='hdrO_zero', z='(rpctransport.Header.mk (W64 0) slice.nil slice.nil)')
    if kind == 'ents': return dict(D='decEnts', T='List EntV', O='entsO', zero='entsO_zero', z='slice.nil')
    raise Exception(kind)

def gen_dec_generic(tn, ty, fields, asm_only=False):
    D, own = OWN[ty]
    ks = [kinfo(k, t) for (_, k, t) in fields]
    out = []
    # assembly lemma
    binds = ' '.join(f'{{a{i} : {k["T"]}}}' for i, k in enumerate(ks))
    prem = []
    for i, ((f, kind, t), k) in enumerate(zip(fields, ks)):
        ref = f'(structFieldRef rpctransport.{ty} go!"{f}" p)'
        if k['O'] is None: prem.append(f'{ref} ↦ a{i}')
        else: prem.append(f'{k["O"]} {ref} a{i}')
    if ty == 'TimeoutReq':
        rec = 'a0'
    else:
        rec = '⟨' + ', '.join(f'a{i}' for i in range(len(fields))) + '⟩'
    out.append(f'theorem asm_{ty} (p : Loc) (Hnn : p ≠ null) {binds} :')
    out.append(f'    ({" ∗ ".join(prem)} : IProp GF) ⊢')
    out.append(f'    ∃ w, p ↦ w ∗ {own} w (DFrac.own 1) {rec} := by')
    pats = []
    mk = []
    for i, k in enumerate(ks):
        if k['O'] is None: pats.append(f'H{i}'); mk.append(f'a{i}')
        else: pats.append(f'⟨%s{i}, H{i}, Hs{i}⟩'); mk.append(f's{i}')
    out.append(f'  iintro ⟨{", ".join(pats)}⟩')
    out.append(f'  iexists (rpctransport.{ty}.mk {" ".join(mk)})')
    out.append(f'  isplitl [{" ".join(f"H{i}" for i in range(len(ks)))}]')
    out.append('  · iapply typedPointsto_combine _ _ _ Hnn')
    out.append('    simp only [TypedPointsto.typedPointstoDef]')
    out.append('    iframe')
    out.append(f'  · unfold {own}' + (' hdrOwn' if own not in ('hdrOwn', 'entOwn', 'timeoutReqOwn') else ''))
    out.append('    iframe')
    out.append('    (try (ipureintro; and_intros <;> rfl))')
    out.append('')
    if asm_only:
        zmk = f'(rpctransport.{ty}.mk ' + ' '.join(k['z'] for k in ks) + ')'
        out.append(f'theorem zero_{ty} : (zero_val rpctransport.{ty} : rpctransport.{ty}) = {zmk} := rfl')
        return '\n'.join(out)
    # decoder
    zmk = f'(rpctransport.{ty}.mk ' + ' '.join(k['z'] for k in ks) + ')'
    out.append(f'theorem zero_{ty} : (zero_val rpctransport.{ty} : rpctransport.{ty}) = {zmk} := rfl')
    out.append('')
    if ty == 'Entry':
        out.append('set_option maxHeartbeats 2000000 in')
    out.append(f'theorem wp_rpcDec_{tn} : decFn (GF := GF) rpcDec_{tn} {D} {zmk}')
    out.append(f'    (fun p v => iprop(∃ w, p ↦ w ∗ {own} w (DFrac.own 1) v)) := by')
    out.append('  intro b bs dq p Φ')
    out.append('  iintro Hb Hp HΦ')
    out.append('  ihave %Hnn := typedPointsto_not_null _ _ _ $$ Hp')
    out.append('  iStructNamed Hp')
    for i, (f, kind, t) in enumerate(fields):
        if f == 'Type':
            out.append(f'  irename : (structFieldRef rpctransport.{ty} go!"Type" p ↦ {ks[i]["z"]} : IProp GF) => FType')
    out.append(f'  dec_hdr {D}')
