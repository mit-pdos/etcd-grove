def nest2(fs, last):
    s = last
    for f in reversed(fs):
        s = f'({f} ++ {s})'
    return s

def gen_enc(tn, ty, fields):
    own = OWN[ty][1]
    out = []
    out.append(f'theorem enc_{ty} : encLaw (hraftCodec (GF := GF)) rpctransport.{ty}.ty {own_of(ty)} {ENC[ty]} := by')
    out.append('  intro p dq w v Ψ')
    out.append('  iintro ⟨Hp, Hown, HΨ⟩')
    out.append('  simp only [hraftCodec]')
    out.append('  iintro %Φ HΦ')
    out.append('  ihave %Hnn := typedPointsto_not_null _ _ _ $$ Hp')
    pat = []
    res = []
    npure = 0
    for i, (f, k, t) in enumerate(fields):
        if k == 'hdr':
            pat.append('⟨hpv, hid, had⟩')
        else:
            pat.append(f'a{i}')
            if k in ('bytes', 'ents'): res.append(f'S{i}')
            else: npure += 1
    out.append(f'  rcases w with ⟨{", ".join(pat)}⟩')
    if ty == 'TimeoutReq':
        out.append('  unfold hdrOwn')
        out.append('  icases Hown with ⟨%Hpv, Hhid, Hhad⟩')
    else:
        out.append(f'  unfold {own} hdrOwn')
        ipat = (['%Hv'] if npure else []) + ['⟨%Hpv, Hhid, Hhad⟩'] + res
        out.append(f'  icases Hown with ⟨{", ".join(ipat)}⟩')
        if npure:
            out.append('  simp only at Hv')
            out.append(f'  obtain ⟨{", ".join(["rfl"] * npure)}⟩ := Hv' if npure > 1 else '  obtain rfl := Hv')
    out.append('  simp only at Hpv')
    out.append('  subst Hpv')
    out.append('  wp_func_call')
    out.append('  wp_call')
    out.append('  wp_auto')
    out.append('  (try (rw [decide_eq_false Hnn]; wp_auto))')
    out.append('  wp_apply wp_rpcPutTag _ as %b ⟨Hb, Hcap⟩')
    out.append('  (try wp_auto)')
    allres = ['Hhid', 'Hhad'] + res
    out.append(f'  wp_apply (wp_rpcEnc_{tn} (dq := dq)) $$ [$Hb $Hcap {" ".join("$" + r for r in allres)}] as %b\' ⟨Hb, Hcap, {", ".join(allres)}⟩')
    out.append('  (try wp_auto)')
    out.append('  iapply HΦ $$ Hb Hcap')
    out.append(f'  unfold {ENC[ty]} tagged')
    out.append(f'  iapply HΨ $$ Hp [{" ".join(allres)}]')
    out.append(f'  (try unfold {own})')
    out.append('  (try unfold hdrOwn)')
    out.append('  dsimp only')
    out.append('  iframe')
    out.append('  (try (ipureintro; and_intros <;> rfl))')
    return '\n'.join(out)

def gen_dec(tn, ty, fields):
    own = OWN[ty][1]
    fs = fexps(ty, fields)
    args = ' '.join(vexp(ty, i) for i in range(len(fields)))
    out = []
    out.append(f'theorem dec_{ty} : decLaw (hraftCodec (GF := GF)) rpctransport.{ty}.ty {own_of(ty)} {ENC[ty]} := by')
    out.append('  intro p v Ψ')
    out.append('  iintro ⟨Hp, HΨ⟩')
    out.append('  simp only [hraftCodec]')
    out.append('  iintro %data %dq %Φ Hd HΦ')
    out.append('  ihave %Hnn := typedPointsto_not_null _ _ _ $$ Hp')
    out.append('  ihave %Hlen := ownSlice_lenZ _ _ _ $$ Hd')
    out.append(f'  have hl : ({ENC[ty]} v).length < 2 ^ 64 := by')
    out.append('    have : sint.Z data.len < 2 ^ 63 := by word')
    out.append('    omega')
    out.append('  wp_func_call')
    out.append('  wp_call')
    out.append('  wp_auto')
    out.append('  wp_apply wp_rpcGetTag data _ dq $$ Hd')
    out.append('  iintro %t %r %ok H')
    out.append(f'  unfold {ENC[ty]} at hl ⊢')
    out.append('  simp only [getTag_tagged _ _ hl]')
    out.append('  icases H with ⟨%Hok, Hr, Hback⟩')
    out.append('  obtain ⟨rfl, rfl⟩ := Hok')
    out.append('  wp_auto')
    out.append('  (try (rw [decide_eq_false Hnn]; wp_auto))')
    out.append(f'  rw [zero_{ty}]')
    out.append(f'  have e : strct [{", ".join(fs)}] = W8 1 :: {nest2(fs, "[]")} := rfl')
    out.append('  rw [e]')
    out.append(f'  wp_apply (wp_rpcDec_{tn}_enc r dq p {args} []) $$ Hr Hp')
    out.append('  iintro %r2 Hr2 Hback2 Hown')
    out.append('  ihave %Hl2 := ownSlice_len _ _ _ $$ Hr2')
    out.append('  wp_auto')
    out.append('  rw [show r2.len = W64 0 by simp at Hl2; word]')
    out.append('  wp_auto')
    out.append('  ihave Hd := Hback $$ [Hback2 Hr2]')
    out.append('  · iapply Hback2 $$ Hr2')
    out.append('  iapply HΦ $$ %interface.nil %true Hd %(by simp) [HΨ Hown]')
    out.append('  · icases Hown with ⟨%w, Hp, Hown⟩')
    out.append('    iapply HΨ $$ Hp Hown')
    out.append('  simp only [ite_true]')
    out.append('  ipureintro; trivial')
    return '\n'.join(out)


