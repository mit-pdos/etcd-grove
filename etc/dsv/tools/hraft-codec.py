# ---- files

def note(t):
    """Put GEN_NOTE at the end of the file's header comment."""
    i = t.index('-/')
    return t[:i] + GEN_NOTE + '\n' + t[i:]

MSGS = ['AppendReq', 'AppendResp', 'SnapReq', 'SnapResp', 'PreVoteReq', 'PreVoteResp', 'VoteReq',
        'VoteResp', 'TimeoutReq', 'TimeoutResp']

def by(names, f, *a):
    return ''.join(f(tn, ty, fs, *a) + '\n\n' for tn, ty, fs in STRUCTS if ty in names)

def files():
    enc = note(T_enc_head) + by(['Header', 'Entry'], gen_enc_struct) + T_enc_mid + by(MSGS, gen_enc_struct) + T_enc_foot
    dec = (note(T_dec_head) + by(['Header', 'Entry'], gen_dec_generic) + T_dec_mid + by(MSGS, gen_dec_generic, True) +
           by(MSGS, gen_dec_enc) + T_enc_foot)
    laws = (note(T_laws_head) + ''.join(gen_enc(tn, ty, fs) + '\n\n' for tn, ty, fs in STRUCTS if ty in ENC) +
            ''.join(gen_dec(tn, ty, fs) + '\n\n' for tn, ty, fs in STRUCTS if ty in ENC) + T_laws_tail + T_enc_foot)
    rcvf = note(T_rcv_head) + gen_laws() + '\n\n' + ''.join(gen_meth(*m) + '\n' for m in METHS) + gen_rcv() + '\n\n' + gen_svc() + '\n' + T_enc_foot
    return {'CodecEnc.lean': enc, 'CodecDec.lean': dec, 'CodecLawsProof.lean': laws, 'CodecRcv.lean': rcvf}

def check_structs():
    """STRUCTS against rpc_gen.go: each struct encoder's fields, in order, with their type numbers."""
    src = open(RPCGEN).read()
    bad = []
    for tn, ty, fs in STRUCTS:
        m = re.search(r'func rpcEnc_%s\(b \[\]byte, v p_rpctransport\.%s\) \[\]byte \{(.*?)\n\}' % (tn, ty), src, re.S)
        if not m:
            bad.append(f'{tn} {ty}: no encoder'); continue
        got = re.findall(r'if rpcSent_(t\d+)\(v\.(\w+)\)', m.group(1))
        want = [(t, f) for (f, k, t) in fs]
        if got != want:
            bad.append(f'{tn} {ty}: rpc_gen.go has {got}, STRUCTS {want}')
    return bad

if __name__ == '__main__':
    check = '--check' in sys.argv[1:]
    bad = check_structs()
    for b in bad: print('hraft-codec: ' + b, file=sys.stderr)
    if bad: sys.exit(1)
    diff = False
    for name, text in files().items():
        p = os.path.join(OUTDIR, name)
        old = open(p).read() if os.path.exists(p) else None
        if check:
            if old != text:
                print(f'hraft-codec: {name} differs from what the script generates', file=sys.stderr); diff = True
        elif old != text:
            open(p, 'w').write(text); print(f'hraft-codec: wrote {name}')
    sys.exit(1 if diff else 0)
