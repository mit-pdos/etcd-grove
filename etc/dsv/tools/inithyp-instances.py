#!/usr/bin/env python3
"""(math-rand-isinit, 2026-11-24; the non-vacuity rule) Write the test-only instance modules of a
kit's `InitHyp` classes: for each names-only package `P` given, `Dsverify/Proof/<P>/InitInstancesLinked.lean`
proves `P.InitHyp GF` (a `theorem`, never an `instance`: etc/dsv/README.md) by walking `P`'s
translated `initialize'` as etc/gen-init.py would if `P` were one of the kit's `PKGS` instead of its
`HYP_INITS`: gen-init's own walk, with its local axioms `opaqueInitsOk` (the untranslated variable
initializers `X.init` run) and `initFuncsOk` (the untranslated `init` functions return), renamed
`localOpaqueInitsOk`/`localInitFuncsOk` and marked test-only. No statement or proof imports these
modules (they are not trust-base roots, notes/dsv-instances.md), so their axioms are in no trust base.

usage: PERENNIAL_DIR=... python3 etc/dsv/tools/inithyp-instances.py KIT PKG... [--check]
       (KIT as etc/dsv/<KIT>.py's `KIT`; PKG among its `HYP_INITS`)
"""
import importlib.util
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
args = [a for a in sys.argv[1:] if not a.startswith('--')]
check = '--check' in sys.argv
kit, targets = args[0], args[1:]
os.chdir(ROOT)
sys.path.insert(0, 'etc')
spec = importlib.util.spec_from_file_location('geninit', 'etc/gen-init.py')
g = importlib.util.module_from_spec(spec)
sys.argv = ['gen-init.py']
spec.loader.exec_module(g)
k = next(x for x in g.DSV_KITS if x.KIT == kit)
for t in targets:
    assert t in k.HYP_INITS, (t, 'not in', kit, 'HYP_INITS')
k.HYP_INITS = [q for q in k.HYP_INITS if q not in targets]
k.PKGS = list(k.PKGS) + [t for t in targets if t not in k.PKGS]
base = (g.inv, g.inst, g.inventory(f'{g.NET_ROOT}/Code'), g.instances(f'{g.NET_ROOT}/Proof/'),
        g.inventory(f'{g.DSV_ROOT}/Code'), g.instances(f'{g.DSV_ROOT}/Proof/'))
raw, need = g.dsv_kit_raw(k, base)
want = {f'{g.DSV_ROOT}/Proof/{g.dirof(t)}/Init.lean': t for t in targets}
made = {p for p, _ in raw}


def imp(m):
    x = m.group(2)
    f = x.replace('.', '/') + '.lean'
    if os.path.exists(f'{g.DSV_ROOT}/{f}') or f'{g.DSV_ROOT}/{f}' in made:
        x = f'{g.DSV_ROOT}.{x}'
    elif os.path.exists(f'{g.NET_ROOT}/{f}'):
        x = f'{g.NET_ROOT}.{x}'
    return m.group(1) + x


# (L1, 2026-11-24) `Proof/runtime/PkgInitExt.lean` is one module for every tree, its `ExternalInit`
# generic (no list of registered packages), so the generated walk's `initLb_of_spec` steps stay as
# gen-init writes them (until then those of a package `Net/`'s inductive did not list became
# `Dsv.initLb_of_spec`, over `Dsverify/`'s `PkgInitDsv`)
def fix(txt):
    return txt


AX_DOC = {
    'opaqueInitsOk': ('**Local axiom (test-only; in no statement\'s trust base): `{p}`\'s untranslated variable '
                      'initializers run.**\nGoose translates them names only (each `X.init` an uninterpreted '
                      'constant of the translation);\nGo runs them at program start and they return '
                      'without panicking (the kit\'s programs start).'),
    'initFuncsOk': ('**Local axiom (test-only; in no statement\'s trust base): `{p}`\'s untranslated `init` '
                    'functions return.**\nGoose translates them names only; Go runs them at program start '
                    'and they return (the kit\'s programs start).'),
}


def transform(p, txt):
    i = txt.index('\nmodule\n')
    head = (f'/-\n**Test only** (the non-vacuity rule; math-rand-isinit, 2026-11-24): `{p}`\'s hypothesis\n'
            f'`InitHyp` (`Dsverify/Proof/{g.dirof(p)}/Init.lean`) holds: its `wp_init` is `local_wp_initialize\'`,\n'
            f'the walk of the translated `initialize\'` etc/gen-init.py makes for a translated package, over\n'
            f'the local axioms below for its names-only initializers. Generated by\n'
            f'`etc/dsv/tools/inithyp-instances.py KIT {p}` (KIT a kit whose `HYP_INITS` holds it). No\n'
            f'statement or proof imports this module.\n-/')
    txt = head + txt[i:]
    txt = txt.replace('\nmodule\n\n', f'\nmodule\n\npublic import Dsverify.Proof.{p}.Init\n', 1)
    for ax, doc in AX_DOC.items():
        txt = re.sub(r'/-- \*\*The trust boundary[^\n]*\n(?:[^\n]*\n)*?[^\n]*-/\naxiom ' + ax + r' :',
                     '/-- ' + doc.format(p=p) + ' -/\naxiom local' + ax[0].upper() + ax[1:] + ' :', txt)
        txt = re.sub(r'\(' + ax + r' ', '(local' + ax[0].upper() + ax[1:] + ' ', txt)
    assert 'trust boundary' not in txt.lower(), p
    txt = txt.replace("theorem wp_initialize'_lb ", "theorem local_wp_initialize'_lb ")
    txt = txt.replace("theorem wp_initialize' ", "theorem local_wp_initialize' ")
    txt = txt.replace("(wp_initialize'_lb get_is_pkg_init Hinit)", "(local_wp_initialize'_lb get_is_pkg_init Hinit)")
    end = f'\nend {p}\n\nend init\n'
    if end not in txt:  # gen-init closes its sections in either order
        end = f'\nend init\n\nend {p}\n'
    assert end in txt, p
    txt = txt.replace(end, f'''
/-- **The instance** (a theorem, not an `instance`: etc/dsv/README.md): `{p}`'s `InitHyp`. -/
theorem initHyp_holds : InitHyp GF := ⟨local_wp_initialize'⟩
{end}''', 1)
    return txt



def merge_linked(init, linked):
    """(gen-init splits a translated package's walk into `Init.lean`, its axioms, and `InitLinked.lean`,
    its `wp_initialize'`: "Import tiers") one text as before the split: the imports of both (the axioms'
    module's, then the linked module's but its import of `Init` itself, which `dsv_hyp_fix` adds), the
    axioms' sections, then the linked module's `init` section."""
    imps = lambda t: re.findall(r'(?m)^public import \S+\n', t)
    li, ii = imps(linked), imps(init)
    seen, out = set(), []
    for x in li[:1] + ii + li[1:]:
        if x.endswith('.Init\n') and x == li[0]:
            continue  # its hypothesis module's import, which dsv_hyp_fix adds
        if x not in seen:
            seen.add(x)
            out.append(x)
    head = init[:init.index(ii[0])]
    body = init[init.index(ii[-1]) + len(ii[-1]):]
    body = body[:body.rindex('\nend Perennial\n')]
    sec = linked[linked.index('\nsection init\n'):]
    return head + ''.join(out) + body + sec


rawd = dict(raw)
bad = []
for path, txt in raw:
    if path not in want:
        continue
    lk = path[:-len('Init.lean')] + 'InitLinked.lean'
    if lk in rawd:
        txt = merge_linked(txt, rawd[lk])
    p = want[path]
    t = transform(p, g.dsv_hyp_fix(path, fix(re.sub(r'(?m)^(public import )(\S+)', imp, txt)), need))
    out = f'{g.DSV_ROOT}/Proof/{g.dirof(p)}/InitInstancesLinked.lean'
    old = open(out).read() if os.path.exists(out) else None
    if old == t:
        continue
    if check:
        bad.append(out)
    else:
        open(out, 'w').write(t)
        print('wrote', out)
if bad:
    for b in bad:
        print('inithyp-instances: differs from the generated:', b)
    sys.exit(1)
