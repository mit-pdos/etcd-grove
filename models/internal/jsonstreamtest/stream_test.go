// Package jsonstreamtest is the differential test of the encoding/json model's streams: the same
// tests run against Go 1.27.3's real encoding/json and against the model (models/encoding/json,
// built in its place by an overlay: run.sh), and each writes a transcript of everything the
// program observes (the values decoded, whether each call failed and how: io.EOF,
// io.ErrUnexpectedEOF, the reader's or writer's own error, another error; every Read call's
// buffer length and what it returned; every Write call's bytes; Decoder.InputOffset and the length
// of Decoder.Buffered after each Decode). The real build writes the golden transcripts
// (testdata/*.golden, `go test -update`); both builds must reproduce them byte for byte.
//
// The program's types are go-vsr's wire format (models/internal/jsonvsr: the vsr-net kit's
// messages, its codec generated by jsongen): vsr's pattern (wire.Encode: one Encoder per message
// written; wire.Decode: one Decoder per message read, its read-ahead lost) and one Decoder reading
// a stream of values, over net.Pipe (a net.Conn) and over a scripted reader that returns chosen
// chunk sizes, with streams cut at every byte (then io.EOF, or a read error), and malformed
// streams.
package jsonstreamtest

