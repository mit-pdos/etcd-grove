#!/usr/bin/env python3
"""Generate difftest's codec for the rpc model (rpc_gen.go, rpc_model_gen.go, rpc_real_gen.go,
rpc_gen_test.go) with kitgen's rpcgen, from RPC below. Usage: ./gen.py [--check]"""
import os
import sys

D = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(D, "..", "..", "kitgen"))
import rpcgen  # noqa: E402
import jsongen  # noqa: E402

RPC = {
    "imports": {"difftest": "dsverify.lab/rpcdifftest"},
    "types": {
        "string": "string",
        "difftest.Args": {"struct": [["A", "uint64"], ["B", "uint64"]]},
        "difftest.Reply": {"struct": [["C", "uint64"]]},
        "difftest.Tags": "map[string]uint64",
        "difftest.Nums": {"struct": [["I", "int"], ["J", "int32"], ["K", "uint8"]]},
    },
    "service": [{"receiver": "*difftest.Arith", "methods": [
        ["Add", "*difftest.Args", "*difftest.Reply"],
        ["Fail", "*difftest.Args", "*difftest.Reply"],
        ["Echo", "string", "*string"],
        ["Keys", "*difftest.Tags", "*difftest.Tags"],
        ["Wait", "*difftest.Args", "*difftest.Reply"],
        ["Signal", "*difftest.Args", "*difftest.Reply"],
        ["Count", "*difftest.Args", "*difftest.Reply"],
        ["Neg", "*difftest.Nums", "*difftest.Nums"],
    ]}, {"receiver": "*difftest.NoMethods", "methods": []},
        {"receiver": "*difftest.Greeter", "methods": [["Hello", "string", "*string"]]}],
}
# the encoding/json model's tests (json_test.go): a frame with a raw payload (go-vsr's), and payloads
JSON = {
    "imports": {"difftest": "dsverify.lab/rpcdifftest"},
    "types": {
        "difftest.Msg": {"struct": [["Type", "uint8", "@type"], ["Data", "json.RawMessage", "data"]]},
        "difftest.Body": {"struct": [["N", "uint64", "n,string"], ["S", "string", "s"], ["Ok", "bool", "ok"],
                                     ["K", "uint32", "k"], ["L", "[]difftest.Item", "l"]]},
        "difftest.Item": {"struct": [["D", "string", "d"]]},
        "[]difftest.Item": {"slice": "difftest.Item"},
    },
}
H = "// Code generated by harness/rpcmodel/difftest/gen.py. DO NOT EDIT.\n\n"
T = rpcgen.Types(RPC)
J = jsongen.Types(JSON)
files = {
    # the package is difftest itself, so its own types are unqualified there: generate into an
    # internal test package that imports it
    "codec/rpc_gen.go": rpcgen.gen_codec_go(T, H, "codec"),
    "codec/rpc_model_gen.go": rpcgen.gen_register_model(H, "codec"),
    "codec/rpc_real_gen.go": rpcgen.gen_register_real(H, "codec"),
    "codec/rpc_gen_test.go": rpcgen.gen_test_go(T, H, "codec"),
    "codec/json_gen.go": jsongen.gen_codec_go(J, H, "codec", True),
    "codec/json_model_gen.go": jsongen.gen_register_model(H, "codec"),
    "codec/json_real_gen.go": jsongen.gen_register_real(H, "codec"),
    "codec/json_gen_test.go": jsongen.gen_test_go(J, H, "codec"),
}
files.update({"codec/" + f: c for f, c in jsongen.gen_extra_files(J, H, "codec").items()})
stale = False
for f, c in files.items():
    p = os.path.join(D, f)
    cur = open(p).read() if os.path.exists(p) else None
    if cur != c:
        if "--check" in sys.argv:
            print(f"not current: {p}")
            stale = True
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w").write(c)
            print(f"wrote {p}")
sys.exit(1 if stale else 0)
