#!/usr/bin/env python3
"""Generate the difftest's protobuf codec (codec/pb_gen.go, pb_model_gen.go, pb_real_gen.go,
pb_gen_test.go) with kitgen's pbgen, from protobuf.toml. Usage: ./gen.py [--check]

The codec package imports the message packages (as a kit's adapter package would); its
Register (codec/register.go) registers the codec with the protobuf model in model builds.
The pbcodec helpers' own tests against the real protowire run from this module:
    go test -tags protowire dsverify.lab/harness/pbcodec"""
import os
import sys
import tomllib

D = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(D, "..", "..", "kitgen"))
import pbgen  # noqa: E402

H = "// Code generated by harness/rpcmodel/grpcdifftest/gen.py from protobuf.toml. DO NOT EDIT.\n\n"
with open(os.path.join(D, "protobuf.toml"), "rb") as fh:
    P = pbgen.Messages(tomllib.load(fh)["protobuf"])
files = {"codec/" + f: c for f, c in pbgen.files(P, H, "codec").items()}
stale = False
for f, c in files.items():
    p = os.path.join(D, f)
    cur = open(p).read() if os.path.exists(p) else None
    if cur != c:
        if "--check" in sys.argv:
            print(f"not current: {p}")
            stale = True
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w").write(c)
            print(f"wrote {p}")
sys.exit(1 if stale else 0)
